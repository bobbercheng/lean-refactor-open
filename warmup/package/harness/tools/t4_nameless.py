def proof_key(proof: str) -> str:
    """sha256 of the stripped proof, 16 hex digits (harness/endstage.sha, t3_suggest.proof_key)."""
    return hashlib.sha256(proof.strip().encode()).hexdigest()[:16]


def probe_hb_cap(heartbeats) -> int:
    """`maxHeartbeats` (thousands) of a probe copy: the copy is the proof with one tactic rewritten, so twice the incumbent's + 1000."""
    try:
        h = max(0, int(heartbeats or 0))
    except (TypeError, ValueError):
        h = 0
    return 2 * h + 1000


