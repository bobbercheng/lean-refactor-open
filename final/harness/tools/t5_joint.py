_BY_LIST = re.compile(r"^by\s+(simp_all|simp|simpa|norm_num|rw|rewrite|dsimp)(?:\s+only)?\s*\[(.*)\]\s*$")


def _list_of(S: Src, st) -> tuple | None:
    """(head, head_end, open, close) of a simp-set / rewrite-list call step: its tactic word, where the word ends, its `[` .. `]` at the
"""
    t = S.code[st.start:st.end]
    m = re.match(r"(" + "|".join(SIMP_HEADS + RW_HEADS) + r")(?![\w'!?])", t)
    if not m:
        return None
    for k in range(st.start + m.end(), st.end):
        if S.code[k] == "[" and S.depth[k] == S.depth[st.start] and k in S.pairs:
            if re.search(r"\b(at|using)\b", S.code[st.start + m.end():k]):
                return None
            return m.group(1), st.start + m.end(), k, S.pairs[k]
    return None


def _item_spans(S: Src, o: int, c: int) -> list[tuple[int, int, str]]:
    """(start, end, text) of each item of the list whose brackets are at o .. c."""
    out, s = [], o + 1
    for k in _depth0(S, o + 1, c, ",") + [c]:
        a, e = s, k
        while a < e and S.proof[a] in " \t\n":
            a += 1
        while e > a and S.proof[e - 1] in " \t\n":
            e -= 1
        if a < e:
            out.append((a, e, S.proof[a:e]))
        s = k + 1
    return out


_BINDS = re.compile(r"(?<![\w'.])(?:(?:have|haveI|let|letI|obtain|set|intro|intros|rintro|fun|generalize|rename_i|case|next|with)\b|λ)((?:[ \t]*"
                    r"(?:" + NAME + r"|_|⟨|⟩|,|\(|\)))*)")


def _locals(S: Src) -> set:
    """Names bound in the declaration (the statement's binders, the proof's have / intro / fun / pattern names): never a lemma head."""
    got = getattr(S, "_locals_cache", None)
    if got is not None:
        return got
    names = set()
    for m in re.finditer(r"[({⦃\[]\s*((?:" + NAME + r"\s+)*" + NAME + r")\s*:", S.statement):
        names |= set(m.group(1).split())
    for m in _BINDS.finditer(S.code):
        names |= set(re.findall(NAME, m.group(1) or ""))
    for m in re.finditer(r"(?m)^[ \t]*(?:·[ \t]*)?(obtain|rcases|rintro|intro|intros)\b([^\n]*)", S.code):
        pat = m.group(2)
        pat = pat.split(":=")[0] if m.group(1) == "obtain" else pat.split(" with ")[-1] if m.group(1) == "rcases" else pat
        names |= {w for w in re.findall(NAME, pat) if "." not in w}
    names.discard("_")
    S._locals_cache = names
    return names


def _item_head(S: Src, txt: str) -> str | None:
    """The head constant of a list item or a have's value (a leading `←` kept; `@` and leading fun / λ binders dropped): `f` of
"""
    t = txt.strip()
    arrow = ""
    if t.startswith("←"):
        arrow, t = "← ", t[1:].strip()
    while True:
        m = re.match(r"(?:fun(?![\w'])|λ)\s*[^=]*?=>\s*", t)
        if not m:
            break
        t = t[m.end():]
    t = t.lstrip("@")
    mi = IDENT.match(t)
    if not mi:
        return None
    h = mi.group(0)
    if h.startswith("λ") or h.split(".")[0] in _locals(S) or h in KEYWORDS or arrow + h == txt.strip():
        return None
    return arrow + h


_CALL_HEAD = re.compile(r"(?<![\w'.])(?:" + "|".join(SIMP_HEADS + RW_HEADS) + r")(?![\w'!?])")


def _inner_calls(S: Src, st0) -> list:
    """List calls inside a step that the tree does not split (a `conv` block, a tactic after `<;>` / `;`, a nested `by` the parser
"""
    out = []
    for m in _CALL_HEAD.finditer(S.code, st0.start + 1, st0.end):
        p = m.start()
        if out and p < out[-1].end:
            continue
        pre = S.code[S.line_start(p):p].rstrip()
        if pre and not pre.endswith(("=>", "<;>", ";", "(", "·", "by", "|", "then", "else", "do")):
            continue                                                                 
        le = S.line_end(p)
        k = m.end()
        while k < min(le, st0.end) and S.code[k] != "[":
            k += 1
        if k >= min(le, st0.end) or k not in S.pairs or S.depth[k] != S.depth[p]:
            continue
        e = S.pairs[k] + 1
        out.append(T3.Step(p, e, S.line(p), S.line(e - 1)))
    return out


def disch_sites(S: Src) -> list[Mol]:
    """D2 (op t5:disch): `have`s (one line or several, a term or a `by` value) whose every later use lies in the lists of simp-set /









"""
    out: list = []
    if not S.tree:
        return out
    for blk in T3._blocks(S.tree[1]):
        calls = []                                                                                                                   
        for i, st0 in enumerate(blk.steps):
            subs = [st0] + [s for ch in st0.children for b in T3._blocks(ch) for s in b.steps]
            subs += [s for s in _inner_calls(S, st0) if all(s.start != x.start for x in subs)]
            for st in subs:
                got = _list_of(S, st)
                if got and got[0] != "rwa":
                    calls.append({"i": i, "st": st, "head": got[0], "head_end": got[1], "o": got[2], "c": got[3],
                                  "items": _item_spans(S, got[2], got[3])})
                elif got is None and st is st0 and "[" in S.code[st.start:st.end] \
                        and re.match(r"(" + "|".join(SIMP_HEADS + RW_HEADS) + r")(?![\w'!?])", S.code[st.start:st.end]):
                    _why("t5:disch", S, st.start, S.code[st.start:st.end][:40], "a location or `using` before the list")
        if not calls:
            continue
        scope_e = blk.steps[-1].end
        haves = {}
        for i, st in enumerate(blk.steps):
            t = S.code[st.start:st.end]
            mh = re.match(r"have(?![\w'])\s*(" + NAME + r")?", t)
            if not mh or not _own_line(S, st):
                continue
            name = mh.group(1) or "this"
            if name in haves:
                continue
            asg = _depth0(S, st.start, st.end, ":=")
            if not asg:
                continue
            if name == "this" and re.search(r"(?<![\w'])(?:have|suffices)\s*(?::|$)", S.code[st.end:scope_e]):
                continue
            if _rebound(S.code[st.end:scope_e], name):
                continue
            haves[name] = {"i": i, "st": st, "val": " ".join(S.proof[asg[0] + 2:st.end].split()), "va": asg[0] + 2, "ve": st.end,
                           "occ": [st.end + x.start() for x in _word_re(name).finditer(S.code[st.end:scope_e])]}
        if not haves:
            continue
        D = {n for n, h in haves.items() if h["occ"]}
        changed = True
        while changed:
            changed = False
            for n in sorted(D):
                h = haves[n]
                ok = all(any(c["i"] > h["i"] and c["o"] < p < c["c"] for c in calls)
                         or any(m != n and m in D and haves[m]["va"] <= p < haves[m]["ve"] for m in haves) for p in h["occ"])
                if not ok:
                    D.discard(n)
                    changed = True
        for n, h in haves.items():
            if n not in D and h["occ"] and any(c["o"] < p < c["c"] for p in h["occ"] for c in calls):
                _why("t5:disch", S, h["st"].start, n, "the have is used outside simp-set lists (and outside deletable haves' values)")

        def closure(base):
            got = set(base)
            grow = True
            while grow:
                grow = False
                for m in D - got:
                    if any(_word_re(x).search(haves[m]["val"]) for x in got):
                        got.add(m)
                        grow = True
            return frozenset(got)
        sets: list = []
        for c in calls:
            base = {n for n in D if any(c["o"] < p < c["c"] for p in haves[n]["occ"])}
            if not base:
                continue
            full = closure(base)
            for s_ in [full] + [closure({n}) for n in sorted(base)]:
                if s_ not in [x for x, _, _ in sets]:
                    sets.append((s_, c, s_ != full))
        for C, T, part in sets:
            out += _disch_variants(S, C, T, calls, haves, part)
    return out


def _disch_tactics(S: Src) -> list[str]:
    """One-word tactics for `(disch := t)`: the proof's own terminal tactics, then the cheap closer table's one-word entries
"""
    got = getattr(S, "_disch_tactics_cache", None)
    if got is not None:
        return got
    out: list[str] = []
    if S.tree:
        doc, top = S.tree
        try:
            own = T3._own_terminals(doc, top)
            d1, _ = T3._closer_lists(own, T3._scope(S.proof, None))
        except Exception:                
            d1 = []
        for key in ("own", "cheap"):
            for c in d1:
                t = str(c.get("text") or "").strip()
                hit = c.get("own") if key == "own" else (not c.get("own") and c.get("cost") == "cheap")
                if hit and re.fullmatch(r"[\w'!?]+", t) and t not in out and len(out) < DISCH_TACTICS:
                    out.append(t)
    S._disch_tactics_cache = out
    return out


def _value_locals(S: Src, val: str, C: frozenset) -> list[str]:
    """The proof's local names a have's value depends on (bound in the declaration, not in the deleted set, not a binder of the value
"""
    bound = set()
    for m in re.finditer(r"(?:fun(?![\w'])|λ)\s*([^=]*?)=>", val):
        bound |= set(re.findall(NAME, m.group(1)))
    loc = _locals(S)
    out = []
    for m in IDENT.finditer(val):
        w = m.group(0).split(".")[0]
        if w in loc and w not in C and w not in bound and w not in out and w != "this":
            out.append(w)
    return out


def _disch_variants(S: Src, C: frozenset, T: dict, calls: list, haves: dict, part: bool = False) -> list[Mol]:
    """The variants of one deletable set C read from the call T (disch_sites); `part`: C is one have's closed set, smaller than the
"""
    words = [_word_re(n) for n in C]
    touched = [c for c in calls if any(w.search(S.code[c["o"]:c["c"]]) for w in words)]
    dels = [_del_lines(S, haves[n]["st"]) for n in sorted(C, key=lambda n: haves[n]["st"].start)]
    heads = [h for h in dict.fromkeys(_item_head(S, haves[n]["val"]) for n in sorted(C, key=lambda n: haves[n]["st"].start)
                                      if not re.match(r"by(?![\w'])", haves[n]["val"])) if h]
    locs = list(dict.fromkeys(w for n in sorted(C, key=lambda n: haves[n]["st"].start) for w in _value_locals(S, haves[n]["val"], C)))

    def rebuild(c, mode, add_heads):
        new_items, stripped, changed = [], False, False
        for a, e, txt in c["items"]:
            tn = _norm(txt)
            if not any(w.search(txt) for w in words):
                new_items.append(txt)
                continue
            changed = True
            if tn in C:
                v = haves[tn]["val"]
                if mode in ("drop", "dropall"):
                    continue
                mb = _BY_LIST.match(v)
                if mode == "merge" and mb:
                    new_items += [x for x in split_items(mb.group(2)) if _norm(x) not in [_norm(y) for y in new_items]]
                    continue
                if v.startswith("by") or any(w.search(v) for w in words):
                    return None
                hd = _item_head(S, v)
                new_items.append(hd if mode == "head" and hd else v)                                                
                continue
            if mode == "dropall":
                continue
            hd = _item_head(S, txt)
            if hd and _norm(hd) not in [_norm(y) for y in new_items]:
                new_items.append(hd)
                stripped = True
        if add_heads:
            for hd in heads + (locs if add_heads == "locals" else []):
                if _norm(hd) not in [_norm(y) for y in new_items]:
                    new_items.append(hd)
        return new_items, stripped, changed
    cands = []
    common = {haves[n]["val"] for n in C}
    disch_cfg = []
    if len(common) == 1:
        mt = re.fullmatch(r"by\s+([\w'!?]+)", next(iter(common)))
        if mt:
            disch_cfg = [(f" (disch := {mt.group(1)})", "disch")]
    for t in _disch_tactics(S):
        if all(t != c for _, c in disch_cfg) and f" (disch := {t})" not in [c for c, _ in disch_cfg]:
            disch_cfg.append((f" (disch := {t})", f"disch:{t}"))
    head_modes = [False] + ([True] if heads else []) + (["locals"] if locs and (heads or locs) else [])
    for add_heads in head_modes:
        for mode in ("drop", "head", "term", "merge", "dropall"):
            built, bad = [], False
            for c in touched:
                r = rebuild(c, mode, add_heads)
                if r is None:
                    bad = True
                    break
                built.append((c, r))
            if bad:
                continue
            rw_bad = False
            eds0, meta_t = list(dels), None
            simp_calls = []
            for c, (new_items, stripped, changed) in built:
                rw = c["head"] in RW_HEADS
                if rw and not stripped:
                    rw_bad = True
                    break
                if new_items:
                    eds0.append(Edit(c["o"] + 1, c["c"], ", ".join(new_items)))
                    if c is T:
                        meta_t = ((c["o"], c["c"]), list(new_items))
                else:
                    a = c["o"]
                    while a > c["head_end"] and S.proof[a - 1] in _BLANK:
                        a -= 1
                    eds0.append(Edit(a, c["c"] + 1, ""))
                if rw:
                    eds0.append(Edit(c["st"].start, c["head_end"], "simp only"))
                simp_calls.append(c)
            if rw_bad:
                continue
            configs = [("", "")]
            tacs = {("simp" if c["head"] in ("simp", "simpa", "dsimp", "field_simp", "norm_num") or c["head"] in RW_HEADS else c["head"])
                    for c in simp_calls}
            if len(tacs) == 1:
                for f, d in DEPTH_FIELDS.get(next(iter(tacs)), []):
                    configs += [(f" ({f} := {d + k})", f"{f}+{k}") for k in range(1, DEPTH_STEPS + 1)]
            configs += disch_cfg
            for cfg, cl in configs:
                eds = list(eds0)
                if cfg:
                    for c in simp_calls:
                        if c["head"] in RW_HEADS:
                            eds = [x for x in eds if not (x.a == c["st"].start and x.e == c["head_end"])]
                            eds.append(Edit(c["st"].start, c["head_end"], "simp only" + cfg))
                            continue
                        at = [x for x in eds if x.a == c["head_end"] and x.e > x.a]                                          
                        if at:
                            eds = [x for x in eds if x is not at[0]] + [Edit(at[0].a, at[0].e, cfg + at[0].new)]
                        else:
                            eds.append(Edit(c["head_end"], c["head_end"], cfg))
                src = "disch/" + ("part-" if part else "") + mode + ("+heads+locals" if add_heads == "locals" else "+heads" if add_heads
                                                                        else "") + (f"-{cl}" if cl else "")
                cands.append((src, eds, meta_t))
    ms, seen_d = [], set()
    note = f"{len(C)} have(s), {len(touched)} call(s) L{T['st'].l0 + 1}"
    for src, eds, meta_t in cands:
        m = S.mol(list(dict.fromkeys(eds)), "t5:disch", src, note=note, groups=(f"disch@{T['st'].start}",), kind="alt")
        if m is None:
            continue
        dt = S.dtok(m.edits)
        d_ = S.decl(m.edits)
        if dt is None or dt < 1 or d_ in seen_d:
            continue
        seen_d.add(d_)
        if meta_t:
            (o, c), items = meta_t
            m.meta = {"list": (o, c), "items": items, "other": [e for e in m.edits if not (e.a == o + 1 and e.e == c)]}
        ms.append((-dt, len(ms), m))
    if cands and not ms:
        _why("t5:disch", S, T["st"].start, ",".join(sorted(C)), "every variant costs tokens")
    ms.sort(key=lambda x: x[:2])
    return [m for _, _, m in ms[:DISCH_SITE_MAX]]


def minimise_variants(S: Src, m: Mol) -> list[Mol]:
    """For a compiling D2 variant: the variant with one item of its rebuilt list removed, per item (the minimisation's singles)."""
    lst, items = (m.meta or {}).get("list"), (m.meta or {}).get("items") or []
    if not lst or len(items) < 2:
        return []
    out = []
    for k in range(len(items)):
        rest = items[:k] + items[k + 1:]
        eds = list(m.meta["other"]) + [Edit(lst[0] + 1, lst[1], ", ".join(rest))]
        v = S.mol(eds, m.op, m.src + "-min", note=f"{m.note}; -{_norm(items[k])[:30]}", groups=m.groups, kind="alt")
        if v is not None:
            v.meta = {"list": lst, "items": rest, "other": list(m.meta["other"]), "drop": [k]}
            out.append(v)
    return out


def minimise_joint(S: Src, m: Mol, droppable: list[int]) -> Mol | None:
    items = (m.meta or {}).get("items") or []
    keep_ = [it for k, it in enumerate(items) if k not in set(droppable)]
    if len(droppable) < 2 or not keep_:
        return None
    lst = m.meta["list"]
    v = S.mol(list(m.meta["other"]) + [Edit(lst[0] + 1, lst[1], ", ".join(keep_))], m.op, m.src + "-min",
              note=f"{m.note}; -{len(droppable)} items", groups=m.groups, kind="alt")
    return v


                                                                                                                                       
class ScreenError(RuntimeError):
    """The incumbent itself does not read ok on the workbench: nothing can be screened against it."""


class Screen:
    """Paired readings on a warm Lean process (module docstring, "screen"). `wb`: harness/workbench.Workbench, or any object with


"""

    def __init__(self, wb, proof: str, *, meter_reading: dict | None = None, max_checks: int = MAX_CHECKS, deadline: float | None = None,
                 log=None):
        self.wb, self.proof = wb, proof.strip()
        self.log = log or (lambda *a: None)
        self.max_checks, self.deadline = int(max_checks), deadline
        self.checks = self.calls = 0
        self.seconds = 0.0
        self.cache: dict = {}
        t = time.time()
        r0 = wb.check([self.proof])[0]
        self.seconds += time.time() - t
        if r0.get("status") != "ok" or r0.get("heartbeats") is None:
            raise ScreenError(f"the incumbent reads {r0.get('status')} on the workbench: {str(r0.get('error') or '')[:160]}")
        self.inc_secs = float(r0.get("seconds") or 0.0)
        self.timeout = max(MIN_TIMEOUT_S, TIMEOUT_MULT * self.inc_secs + 4.0)
        mr = meter_reading or {}
        tokens = int(mr.get("tokens") if mr.get("tokens") is not None else r0["tokens"])
        hb = int(mr.get("heartbeats") if mr.get("heartbeats") is not None else r0["heartbeats"])
        Z = float(mr.get("Z") if mr.get("Z") is not None else 100.0)
        sc = mr.get("score_exact")
        sc = float(sc) if sc is not None else float(wb.metrics(tokens, hb, Z)["score_exact"])
        self.inc = {"tokens": tokens, "heartbeats": hb, "Z": Z, "score": sc}
        self.ref_hb = int(r0["heartbeats"])
        self.first = r0
        try:
            from harness.batch_screen import hb_bound
            self.max_hb = hb_bound(lambda t_, h_, z_: wb.metrics(t_, h_, z_), {"score_exact": sc, "heartbeats": hb})
        except Exception:                
            self.max_hb = None

    def left(self) -> int:
        if self.deadline is not None and time.time() >= self.deadline:
            return 0
        return max(0, self.max_checks - self.checks)

    def _annotate(self, r: dict) -> dict:
        r = dict(r)
        if r.get("status") == "ok" and r.get("heartbeats") is not None and r.get("tokens") is not None:
            d_hb = int(r["heartbeats"]) - self.ref_hb
            hb = self.inc["heartbeats"] + d_hb
            m = self.wb.metrics(int(r["tokens"]), hb, self.inc["Z"])
            r.update(d_hb=d_hb, hb_est=hb, est=float(m["score_exact"]), d_score=float(m["score_exact"]) - self.inc["score"],
                     d_tokens=self.inc["tokens"] - int(r["tokens"]))
            inc = {"score": self.inc["score"], "tokens": self.inc["tokens"], "heartbeats": self.inc["heartbeats"], "Z": self.inc["Z"]}
            r["pass"] = decide(inc, {"score": r["est"], "tokens": int(r["tokens"]), "heartbeats": hb, "Z": self.inc["Z"]})[0]
        return r

    def check(self, decls: list[str]) -> list[dict]:
        keys = [d.strip() for d in decls]
        todo = [k for k in dict.fromkeys(keys) if k not in self.cache and k != self.proof]
        i = 0
        while i < len(todo):
            n = min(CHUNK, self.left())
            if n <= 0:
                break
            chunk = todo[i:i + n]
            i += n
            t = time.time()
            rs = self.wb.check([self.proof] + chunk, timeout=self.timeout, max_heartbeats=self.max_hb)
            self.seconds += time.time() - t
            self.calls += 1
            self.checks += len(chunk)
            if rs and rs[0].get("status") == "ok" and rs[0].get("heartbeats") is not None:
                self.ref_hb = int(rs[0]["heartbeats"])
            for k, r in zip(chunk, rs[1:]):
                self.cache[k] = self._annotate(r)
        return [self.cache.get(k) or {"status": "budget", "ok": False} for k in keys]


                                                                                                                                       
def _round_robin(groups: dict) -> list:
    """Items of {key: [items]} interleaved: the first of every key (in key order), then the second, ..."""
    out, k = [], 0
    lists = [v for v in groups.values() if v]
    while any(k < len(v) for v in lists):
        out += [v[k] for v in lists if k < len(v)]
        k += 1
    return out


def _err_sites(S: Src, m: Mol, r: dict, line0: int | None) -> tuple[set, set]:
    """(base lines, identifiers) an error of the reading points at: the error's line mapped back through the molecule's edits, and
"""
    lines, idents = set(), set()
    if line0 is None:
        return lines, idents
    cand = S.decl(m.edits)
    starts = [0] + [i + 1 for i, ch in enumerate(cand) if ch == "\n"]
    for e in r.get("errors") or []:
        mm = re.match(r"(\d+):(\d+): (.*)", str(e), re.S)
        if not mm:
            continue
        dl = int(mm.group(1)) - line0
        if 1 <= dl <= len(starts):
            lines.add(S.line(to_base(m.edits, starts[dl - 1])))
        idents |= set(re.findall(r"'([^'\s]+)'", mm.group(3)[:400])) | set(re.findall(r"`([^`\s]+)`", mm.group(3)[:400]))
    return lines, idents


_UNREPAIRABLE = re.compile(r"unexpected token|expected (?:term|token|'|`)|don't know how to synthesize|typeclass instance problem is stuck|"
                           r"timeout|heartbeats|maximum recursion", re.I)


def _repairable(r: dict) -> bool:
    """A failing reading whose first error another atom could mend: not a parse error, an unassigned placeholder, a stuck instance
"""
    es = r.get("errors") or []
    return bool(es) and not _UNREPAIRABLE.search(str(es[0])[:300])


def _touches(S: Src, p: Mol, lines: set, idents: set) -> bool:
    for e in p.edits:
        if any(S.line(e.a) - 1 <= l <= S.line(max(e.a, e.e - 1)) + 1 for l in lines):
            return True
        if idents and any(_word_re(i).search(S.proof[e.a:e.e] + " " + e.new) for i in idents):
            return True
    return False


def _t4_probe(S: Src, wb, scr, stats: dict, log) -> dict:
    """T4's name probe (harness/tools/t4_nameless.probe) on the workbench: {"t4_probe", "t4_probe_for"} for this proof, or {} (no site
"""
    try:
        from harness.tools import t4_nameless as T4
    except ImportError:
        return {}
    if not any(s_.get("used") for s_ in T4.sites_summary(S.proof, S.statement)):
        return {}

    def compile_batch(texts):
        if scr.left() <= 0:
            return [None] * len(texts)
        try:
            rs = wb.check(list(texts), timeout=scr.timeout, messages=True)
        except TypeError:                                                           
            return [None] * len(texts)
        stats["probe_checks"] = stats.get("probe_checks", 0) + len(texts)
        return [r.get("messages") if isinstance(r.get("messages"), list) else None for r in rs]
    try:
        t = time.time()
        got = T4.probe(S.proof, S.statement, compile_batch, stats=stats.setdefault("t4_probe", {}), log=log) or {}
        scr.seconds += time.time() - t
        return got
    except Exception as e:                                                  
        log(f"t5 search: t4 probe failed ({type(e).__name__}: {str(e)[:120]})")
        return {}


def search(proof: str, statement: str, wb, *, meter_reading: dict | None = None, exchange=None, ctx: dict | None = None,
           stats: dict | None = None, log=None, deadline: float | None = None, max_checks: int = MAX_CHECKS, n_out: int = N_OUT,
           stage_caps: dict | None = None, trace: list | None = None) -> dict:
    """The joint-edit search on the workbench (module docstring, "search"): {"t5_found": [{"op", "decl", "note", "est"}],

"""
    t0 = time.time()
    st = stats if stats is not None else {}
    log = log or (lambda *a: None)
    S = Src(proof.strip(), statement)
    if not S.ok:
        return {}
    ops = _ops(ctx)
    caps = dict(STAGE_CAPS, **(stage_caps or {}))
    scr = Screen(wb, S.proof, meter_reading=meter_reading, max_checks=max_checks, deadline=deadline, log=log)
    line0 = getattr(wb, "decl_line0", None)
    if NAMELESS_PROBE and {"t5:chain", "t5:repair"} & set(ops) and not (ctx or {}).get("t4_probe_for") == proof_key(S.proof):
        got_p = _t4_probe(S, wb, scr, st, log)
        if got_p:
            ctx = dict(ctx or {}, **got_p)
    gen0 = time.time()
    el = elide_atoms(S) if "t5:elide" in ops or "t5:chain" in ops or "t5:repair" in ops else []
    fam = family_atoms(S, exchange=exchange, ctx=ctx) if {"t5:chain", "t5:repair"} & set(ops) else []
    alts = class_unions(S, el) if "t5:elide" in ops else []
    if {"t5:shared", "t5:collapse"} & set(ops):
        alts += [m for m in shared_sites(S, ctx) if m.op in ops]
    if "t5:disch" in ops:
        alts += disch_sites(S)
    seen = {S.proof}

    def dd(ms):
        out = []
        for m in ms:
            d = S.decl(m.edits).strip()
            if d not in seen:
                seen.add(d)
                out.append(m)
        return out
    alts = dd(alts)
    atoms = dd(el + fam)
    dt = {id(m): S.dtok(m.edits) or 0 for m in alts + atoms}
    st_gen = {"atoms_family": len([m for m in atoms if m.op == "single"]), "atoms_elide": len([m for m in atoms if m.op != "single"]),
              "alts": len(alts), "gen_seconds": round(time.time() - gen0, 2)}
    res: dict = {}                           

    def note(m, r):
        if trace is not None:
            trace.append({"op": m.op, "src": m.label(), "kind": m.kind, "status": r.get("status"), "error": str(r.get("error") or "")[:240],
                          "d_score": r.get("d_score"), "d_tokens": r.get("d_tokens"), "parts": len(m.parts)})

    def run(ms):
        ms = [m for m in ms if S.decl(m.edits).strip() not in res]
        rs = scr.check([S.decl(m.edits) for m in ms])
        got = []
        for m, r in zip(ms, rs):
            if r.get("status") == "budget":
                continue
            res[S.decl(m.edits).strip()] = (m, r)
            note(m, r)
            got.append((m, r))
        return got
    stage: dict = {}
                                                                                        
    by_site: dict = {}
    for m in sorted(alts, key=lambda x: -dt[id(x)]):
        by_site.setdefault(min(m.groups) if m.groups else m.src, []).append(m)
    got = run(_round_robin(by_site)[:caps["alts"]])
    stage["alts"] = len(got)
                                                                                  
    by_src: dict = {}
    for m in sorted(atoms, key=lambda x: -dt[id(x)]):
        by_src.setdefault(m.src.split(":")[0] if m.op == "single" else m.src, []).append(m)
    got = run(_round_robin(by_src)[:caps["atoms"]])
    stage["atoms"] = len(got)
                                                                                                                            
    mins = 0
    dz = sorted([(m, r) for m, r in res.values() if m.op == "t5:disch" and r.get("status") == "ok" and (m.meta or {}).get("list")],
                key=lambda x: -x[1].get("d_score", 0.0))[:2]
    for m, r in dz:
        if mins >= caps["minimise"]:
            break
        vs = minimise_variants(S, m)[:max(0, caps["minimise"] - mins)]
        g1 = run(vs)
        mins += len(g1)
        drop = [v.meta["drop"][0] for v, rv in g1 if rv.get("status") == "ok"]
        j = minimise_joint(S, m, drop)
        if j is not None and mins < caps["minimise"]:
            mins += len(run([j]))
    stage["minimise"] = mins
                                                                                                                               
    rep = 0
    if "t5:repair" in ops:
        pool = [m for m in atoms] + [m for m, r in res.values() if m.kind == "alt" and r.get("status") == "ok" and not m.parts]
        for m in pool:
            dt.setdefault(id(m), S.dtok(m.edits) or 0)
        fails = sorted([(m, r) for m, r in res.values() if r.get("status") == "fail" and not m.parts and _repairable(r)],
                       key=lambda x: -dt.get(id(x[0]), 0))
        st["repair_skipped"] = st.get("repair_skipped", 0) + sum(1 for m, r in res.values() if r.get("status") == "fail" and not m.parts
                                                                  and not _repairable(r))
        pairs = []
        for m, r in fails:
            lines, idents = _err_sites(S, m, r, line0)
            if not lines and not idents:
                continue
            ps = [p for p in pool if p is not m and compatible(m, p) and _touches(S, p, lines, idents)]
            ps.sort(key=lambda p: -dt.get(id(p), 0))
            for p in ps[:REPAIR_PARTNERS]:
                u = union([m, p], op="t5:repair")
                if u is not None:
                    pairs.append((dt.get(id(m), 0) + dt.get(id(p), 0), u, (m, p)))
        pairs.sort(key=lambda x: -x[0])
        cap2 = (2 * caps["repair"]) // 3
        g2 = run([u for _, u, _ in pairs[:cap2]])
        rep += len(g2)
        tri = []
        for u, r in g2:
            if r.get("status") != "fail" or not _repairable(r):
                continue
            lines, idents = _err_sites(S, u, r, line0)
            ps = [p for p in pool if compatible(u, p) and _touches(S, p, lines, idents) and p.label() not in u.parts]
            ps.sort(key=lambda p: -dt.get(id(p), 0))
            for p in ps[:REPAIR_TRIPLES]:
                v = union([u, p], op="t5:repair")
                if v is not None:
                    tri.append(v)
        rep += len(run(tri[:max(0, caps["repair"] - rep)]))
    stage["repair"] = rep
                                                                                                               
    ch = 0
    best_chain = None
    if "t5:chain" in ops:
        pool = [(m, r) for m, r in res.values() if r.get("status") == "ok" and r.get("d_score", -1) > CHAIN_FLOOR
                and (r.get("d_tokens", 0) >= 1 or r.get("d_hb", 0) <= -HB_EPS)]
        pool.sort(key=lambda x: (-x[1]["d_score"], -dt.get(id(x[0]), 0)))
        rest = [m for m, _ in pool]
        acc, acc_est = None, scr.inc["score"]
        while rest and ch < caps["chain"] and scr.left() > 0:
            seq, cur = [], acc
            for m in rest:
                u = m if cur is None else union([cur, m])
                if u is None:
                    continue
                seq.append((m, u))
                cur = u
                if len(seq) >= max(1, min(CHAIN_BATCH, caps["chain"] - ch)):
                    break
            if not seq:
                break
            c0 = scr.checks
            rs = scr.check([S.decl(u.edits) for _, u in seq])
            ch += scr.checks - c0
            for (m, u), r in zip(seq, rs):
                k = S.decl(u.edits).strip()
                if r.get("status") != "budget" and k not in res:
                    res[k] = (u, r)
                    note(u, r)
            best_i = fail_i = None
            n_read = 0
            for i, r in enumerate(rs):
                if r.get("status") == "budget":
                    break
                n_read = i + 1
                if r.get("status") != "ok":
                    fail_i = i
                    break
                if r.get("est", -1e9) > acc_est + 1e-9 and (best_i is None or r["est"] > rs[best_i]["est"]):
                    best_i = i
            if n_read == 0:
                break
                                                                                                                                      
                                                                                                                           
            if best_i is not None:
                acc, acc_est = seq[best_i][1], rs[best_i]["est"]
            drop = {id(m) for m, _ in seq[:n_read]}
            rest = [m for m in rest if id(m) not in drop]
        if acc is not None and len(acc.parts) >= 2:
            best_chain = acc
    stage["chain"] = ch
               
    found, seen2 = [], set()
    rows = []
    for d, (m, r) in res.items():
        if m.op == "single" or m.op not in ops or r.get("status") != "ok":
            continue
        if not (r.get("d_score", 0.0) > 0.0 and (r.get("d_tokens", 0) >= 1 or r.get("d_hb", 0) <= -HB_EPS)):
            continue
        if m.op == "t5:chain" and len(m.parts) < 2:
            continue
        rows.append((not r.get("pass"), -r["d_score"], d, m, r))
    rows.sort(key=lambda x: x[:3])
    per_site: dict = {}
    for _, _, d, m, r in rows:
        site = (m.op, m.groups) if m.groups else d
        if d in seen2 or len(found) >= n_out or per_site.get(site, 0) >= PER_SITE_OUT:
            continue
        per_site[site] = per_site.get(site, 0) + 1
        seen2.add(d)
        found.append({"op": m.op, "decl": d, "expensive": m.expensive,
                      "note": f"{m.src}{(' ' + m.note) if m.note else ''}; est {r['d_score']:+.4f} ({r['d_tokens']:+d} tok, "
                              f"{-r['d_hb']:+d} hb)" + (f"; parts {len(m.parts)}" if len(m.parts) >= 2 else ""),
                      "est": {"d_score": round(r["d_score"], 6), "d_tokens": r["d_tokens"], "d_heartbeats": -r["d_hb"],
                              "pass": bool(r.get("pass"))}})                                                                   
    st.update({k: st.get(k, 0) + v for k, v in st_gen.items() if isinstance(v, int)})
    st["gen_seconds"] = round(st.get("gen_seconds", 0.0) + st_gen["gen_seconds"], 2)
    st["searches"] = st.get("searches", 0) + 1
    st["checks"] = st.get("checks", 0) + scr.checks
    st["calls"] = st.get("calls", 0) + scr.calls
    st["wb_seconds"] = round(st.get("wb_seconds", 0.0) + scr.seconds, 1)
    st["seconds"] = round(st.get("seconds", 0.0) + time.time() - t0, 1)
    st["found"] = st.get("found", 0) + len(found)
    for k, v in stage.items():
        st.setdefault("stages", {})[k] = st.get("stages", {}).get(k, 0) + v
    st["compiled"] = st.get("compiled", 0) + sum(1 for _, r in res.values() if r.get("status") == "ok")
    st["budget_out"] = bool(scr.left() == 0)
    if best_chain is not None:
        st["chain_parts"] = max(st.get("chain_parts", 0), len(best_chain.parts))
    log(f"t5 search: {len(alts)} variants, {len(atoms)} atoms; {scr.checks} readings in {scr.calls} calls ({scr.seconds:.0f} s); "
        f"{len(found)} survivor(s)")
    return {"t5_found": found, "t5_found_for": proof_key(S.proof)}


                                                                                                                                      
def _timeout(ctx: dict | None):
    cs = (ctx or {}).get("compile_s")
    if isinstance(cs, (int, float)) and cs > 0:
        return max(T3.MIN_TIMEOUT_S, T3.TIMEOUT_MULT * float(cs))
    return T3.DEFAULT_TIMEOUT_S


def candidates(proof: str, statement: str, *, exchange: float | None = None, max_per_op: int = MAX_PER_OP,
               ctx: dict | None = None) -> list[dict]:
    """[{"op", "decl", "note"}] (module docstring, "candidates"): the search's survivors for this proof (ctx["t5_found"] with
"""
    ops = _ops(ctx)
    ctx = ctx or {}
    out, per = [], {}
    if ctx.get("t5_found_for") == proof_key(proof) and isinstance(ctx.get("t5_found"), list):
        for c in ctx["t5_found"]:
            if not isinstance(c, dict) or c.get("op") not in ops or not isinstance(c.get("decl"), str):
                continue
            d = c["decl"]
            if split_declaration(d, statement) is None or d.strip() == proof.strip() or per.get(c["op"], 0) >= max_per_op:
                continue
            per[c["op"]] = per.get(c["op"], 0) + 1
            item = {"op": c["op"], "decl": d, "note": str(c.get("note") or "")[:300]}
            if c.get("expensive"):
                item["timeout_s"] = _timeout(ctx)
            out.append(item)
        return out
    S = Src(proof, statement)
    if not S.ok:
        return []
    ms = []
    if "t5:elide" in ops:
        ms += class_unions(S, elide_atoms(S))
    if {"t5:shared", "t5:collapse"} & set(ops):
        ms += [m for m in shared_sites(S, ctx) if m.op in ops]
    if "t5:disch" in ops:
        ms += disch_sites(S)
    rows, seen = [], {proof.strip()}
    for i, m in enumerate(ms):
        d = S.decl(m.edits)
        dt = S.dtok(m.edits)
        if d.strip() in seen or dt is None or dt < 1:
            continue
        seen.add(d.strip())
        rows.append((-dt, OPS.index(m.op), i, m, d))
    rows.sort(key=lambda x: x[:3])
    for _, _, _, m, d in rows:
        if per.get(m.op, 0) >= min(max_per_op, FALLBACK_PER_OP):
            continue
        per[m.op] = per.get(m.op, 0) + 1
        item = {"op": m.op, "decl": d, "note": f"{m.src}{(' ' + m.note) if m.note else ''}; unscreened"}
        if m.expensive:
            item["timeout_s"] = _timeout(ctx)
        out.append(item)
    return out


def generated(proof: str, statement: str, ctx: dict | None = None) -> dict:
    """What the search would read, without Lean (the CLI and the tests): {"atoms": [...], "alts": [...]} as {"op", "src", "note",
"""
    S = Src(proof, statement)
    if not S.ok:
        return {"atoms": [], "alts": []}
    el = elide_atoms(S)
    alts = class_unions(S, el) + shared_sites(S, ctx) + disch_sites(S)

    def row(m):
        return {"op": m.op, "src": m.src, "note": m.note, "dtok": S.dtok(m.edits), "decl": S.decl(m.edits)}
    return {"atoms": [row(m) for m in el], "alts": [row(m) for m in alts]}


def explain(proof: str, statement: str, ctx: dict | None = None) -> dict:
    """Coverage diagnosis (no Lean): per op class the sites generated ({"line", "src", "dtok"}) and the nearby constructs each

"""
    S = Src(proof.strip(), statement)
    if not S.ok:
        return {"ok": False}
    _TL.why = []
    try:
        el = elide_atoms(S)
        alts = class_unions(S, el) + shared_sites(S, ctx) + disch_sites(S)
        fam = family_atoms(S, ctx=ctx)
    finally:
        why, _TL.why = _TL.why, None
    sites: dict = {}
    for m in el + alts:
        cls = m.op + "/" + m.src.split("/", 1)[-1].split("-")[0]
        sites.setdefault(cls, []).append({"line": S.line(m.edits[0].a) + 1, "src": m.src, "dtok": S.dtok(m.edits), "kind": m.kind})
    fams: dict = {}
    for m in fam:
        fams[m.src] = fams.get(m.src, 0) + 1
    try:
        from harness.tools import t4_nameless as T4
        nl = [{"op": s_["op"], "line": s_["line"], "used": bool(s_.get("used"))} for s_ in T4.sites_summary(S.proof, statement)]
    except Exception:                
        nl = []
    return {"ok": True, "tree": S.tree is not None, "tokens": S.tok0, "sites": sites, "skips": why, "family_atoms": fams,
            "nameless": nl}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--file", required=True, help="the declaration (statement + proof)")
    ap.add_argument("--statement-file", required=True)
    ap.add_argument("--sites", action="store_true", help="print the generated atoms and site variants (no Lean)")
    a = ap.parse_args(argv)
    proof = Path(a.file).read_text().strip()
    statement = Path(a.statement_file).read_text().strip()
    if a.sites:
        g = generated(proof, statement)
        for k in ("atoms", "alts"):
            for r in g[k]:
                print(json.dumps(dict(r, kind=k), ensure_ascii=False))
        return 0
    for c in candidates(proof, statement):
        print(json.dumps(c, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
