def _load_heads() -> set:
    """The heads of HEADS present on every toolchain of the generated table (empty when it is missing: T4 then writes nothing)."""
    try:
        t = json.loads(TABLE_PATH.read_text())
    except (OSError, ValueError):
        return set()
    tcs = set(t.get("toolchains") or [])
    pres = t.get("present") or {}
    return {h for h in HEADS if tcs and tcs <= set(pres.get(h) or [])}


