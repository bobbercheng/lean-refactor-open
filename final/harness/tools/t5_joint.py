@dataclass(frozen=True)
class Edit:
    """One contiguous replacement of the declaration text: [a, e) -> new (offsets in the incumbent declaration)."""
    a: int
    e: int
    new: str


def apply_edits(text: str, edits) -> str:
    for ed in sorted(edits, key=lambda x: (x.a, x.e), reverse=True):
        text = text[:ed.a] + ed.new + text[ed.e:]
    return text


def disjoint(x: Edit, y: Edit) -> bool:
    """Two edits can be applied together in either order: their spans do not overlap; touching spans only when both replace text."""
    if x.e < y.a or y.e < x.a:
        return True
    if x.e == y.a or y.e == x.a:
        return x.a < x.e and y.a < y.e
    return False


def diff_edits(old: str, new: str) -> tuple:
    """The edits turning `old` into `new`: line hunks (difflib), each shrunk to its smallest changed span."""
    a, b = old.splitlines(keepends=True), new.splitlines(keepends=True)
    off = [0]
    for l in a:
        off.append(off[-1] + len(l))
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        s, e = off[i1], off[i2]
        so, sn = old[s:e], "".join(b[j1:j2])
        p = 0
        while p < min(len(so), len(sn)) and so[p] == sn[p]:
            p += 1
        q = 0
        while q < min(len(so), len(sn)) - p and so[-1 - q] == sn[-1 - q]:
            q += 1
        out.append(Edit(s + p, e - q, sn[p:len(sn) - q]))
    return tuple(out)


def to_base(edits, off: int) -> int:
    """An offset of apply_edits(base, edits) mapped back to the base text (inside a replacement: the replaced span's start)."""
    delta = 0
    for ed in sorted(edits, key=lambda x: (x.a, x.e)):
        s = ed.a + delta
        if off < s:
            break
        if off < s + len(ed.new):
            return ed.a
        delta += len(ed.new) - (ed.e - ed.a)
    return off - delta


@dataclass
class Mol:
    """A molecule: edits applied together or not at all. op: the T5 op it is proposed under ("single": a family's single-site edit, a

"""
    edits: tuple
    op: str
    src: str
    note: str = ""
    groups: frozenset = frozenset()
    kind: str = "atom"
    parts: tuple = ()
    expensive: bool = False
    meta: dict = field(default_factory=dict)

    def label(self) -> str:
        return self.src + (f" [{self.note}]" if self.note else "")


def compatible(m1: Mol, m2: Mol) -> bool:
    if m1.groups & m2.groups:
        return False
    return all(disjoint(x, y) for x in m1.edits for y in m2.edits)


def union(mols, op: str = "t5:chain") -> Mol | None:
    """One molecule holding every edit of `mols` (None when two of them overlap or share a site)."""
    eds: list = []
    groups: set = set()
    parts: list = []
    exp = False
    for m in mols:
        if m.groups & groups or not all(disjoint(x, y) for x in m.edits for y in eds):
            return None
        eds += list(m.edits)
        groups |= m.groups
        parts += list(m.parts or (m.label(),))
        exp = exp or m.expensive
    return Mol(tuple(sorted(eds, key=lambda x: (x.a, x.e))), op, "+".join(sorted({p.split(" [")[0] for p in parts})), "",
               frozenset(groups), "alt", tuple(parts), exp)


                                                                                                                                       
class Src:
    """The incumbent declaration: comment / string mask, bracket pairs, depths, lines, T3's tactic tree (None for term mode)."""

    def __init__(self, proof: str, statement: str):
        self.proof, self.statement = proof, statement
        body = split_declaration(proof, statement)
        self.ok = body is not None
        if not self.ok:
            return
        self.body, self.off0 = body, len(proof) - len(body)
        self.mask = _mask(proof)
        self.pairs = _pairs(proof, self.mask)
        self.rpairs = {j: i for i, j in self.pairs.items()}
        self.code = "".join(" " if m else c for c, m in zip(proof, self.mask))
        self.tok0 = count_tokens(body)
        self.line0 = [0] + [i + 1 for i, c in enumerate(proof) if c == "\n"]
        depth, d = [0] * (len(proof) + 1), 0
        for i, c in enumerate(self.code):
            depth[i] = d
            if c in "([{⟨" and i in self.pairs:
                d += 1
            elif c in ")]}⟩" and i in self.rpairs:
                d -= 1
        depth[len(proof)] = d
        self.depth = depth
        try:
            self.tree = T3.parse(proof, statement)
        except Exception:                                                                                          
            self.tree = None

    def line(self, pos: int) -> int:
        return bisect.bisect_right(self.line0, pos) - 1

    def line_start(self, pos: int) -> int:
        return self.line0[self.line(pos)]

    def line_end(self, pos: int) -> int:
        e = self.proof.find("\n", pos)
        return len(self.proof) if e < 0 else e

    def decl(self, edits) -> str:
        return apply_edits(self.proof, edits)

    def dtok(self, edits) -> int | None:
        body = split_declaration(self.decl(edits), self.statement)
        return None if body is None else self.tok0 - count_tokens(body)

    def mol(self, edits, op, src, note="", groups=(), kind="atom", expensive=False) -> Mol | None:
        """A molecule over this declaration, or None when an edit touches the statement or nothing changes."""
        edits = tuple(sorted((e for e in edits if not (e.a == e.e and not e.new)), key=lambda x: (x.a, x.e)))
        if not edits or any(e.a < self.off0 for e in edits):
            return None
        for i, x in enumerate(edits):
            if any(not disjoint(x, y) for y in edits[i + 1:]):
                return None
        return Mol(edits, op, src, note, frozenset(groups), kind, (), expensive, {})


                                                                                                                                      
_ATOMIC = re.compile(r"^(?:@?[^\W\d][" + _IDC + r".]*|\d+(?:\.\d+)?|_|‹[^›]*›|\?_)$")
BINDER_WORDS = ("fun", "λ", "∀", "∃", "∃!", "Π", "Σ")
HEADER_WORDS = ("have", "haveI", "let", "letI", "obtain", "intro", "intros", "rintro", "rcases", "cases", "induction", "match", "set",
                "suffices", "case", "next", "generalizing", "with", "theorem", "lemma", "def", "instance", "abbrev", "example")
_AFTER_WORDS = ("at", "with", "using", "generalizing", "<;>", "=>", "then", "else", "from")


def _atomic(t: str) -> bool:
    """A term that needs no parentheses as an argument: an identifier, a numeral, a hole, or one bracketed group."""
    t = t.strip()
    if _ATOMIC.match(t):
        return True
    if t and t[0] in "([⟨{" and t[-1] in ")]⟩}":
        m = _mask(t)
        return _pairs(t, m).get(0) == len(t) - 1
    return False


def _prev_word(s: str) -> str:
    m = re.search(r"([^\s(\[⟨,]+)\s*$", s)
    return m.group(1) if m else ""


def _slot(S: Src, a: int, e: int) -> bool:
    """Does the span [a, e) stand as a whole term (a tactic's argument, a list item, a bracket's content, a definition's value), so
"""
    i = a - 1
    while i >= 0 and S.proof[i] in _BLANK:
        i -= 1
    if i < 0 or S.proof[i] == "\n" or S.code[i] in "([⟨,{|" or S.proof[i - 1:i + 1] == ":=":
        ok_b = True
    else:
        ok_b = _prev_word(S.code[S.line_start(a):a]) in KEYWORDS
    if not ok_b:
        return False
    j = e
    while j < len(S.proof) and S.proof[j] in _BLANK:
        j += 1
    if j >= len(S.proof) or S.proof[j] == "\n" or S.code[j] in ")]⟩,}":
        return True
    return any(S.code.startswith(w, j) and (j + len(w) >= len(S.code) or not re.match(r"[\w']", S.code[j + len(w)]))
               for w in _AFTER_WORDS)


def _wrap(S: Src, a: int, e: int, term: str) -> str:
    """`term` written in place of the span [a, e): bare when atomic or when the span is a whole-term slot, else parenthesized; a span
"""
    t = term.strip()
    if _atomic(t):
        return t
    if e < len(S.proof) and S.proof[e] == ".":
        return f"({t})"
    return t if _slot(S, a, e) else f"({t})"


def _binder_ctx(S: Src, i: int) -> str | None:
    """The bracket group opening at i: "binder" (a fun / quantifier binder group), "header" (a have / let / pattern / declaration
"""
    ls = S.line_start(i)
    pre = S.code[ls:i]
    for _ in range(16):
        pre = pre.rstrip()
        if not pre:
            return None
        if pre[-1] in ")}]⦄" and (ls + len(pre) - 1) in S.rpairs:
            pre = pre[:S.rpairs[ls + len(pre) - 1] - ls]
            continue
        m = re.search(r"(?:^|[\s(⟨\[,])(" + "|".join(re.escape(w) for w in BINDER_WORDS) + r")$", pre)
        if m:
            return "binder"
        w = _prev_word(pre)
        if w in HEADER_WORDS:
            return "header"
        m = re.search(r"(?:" + NAME + r"|_)$", pre)
        if m and m.start() > 0 and pre[m.start() - 1] in " \t":
            pre = pre[:m.start()]
            continue
        return None
    return None


def _depth0(S: Src, a: int, e: int, ch: str) -> list[int]:
    """Positions of `ch` (a 1- or 2-character token) in [a, e) at the bracket depth of a, outside comments and strings."""
    d0 = S.depth[a]
    out = []
    k = a
    while k < e:
        if S.depth[k] == d0 and S.code.startswith(ch, k):
            out.append(k)
            k += len(ch)
            continue
        k += 1
    return out


                                                                                                                                       
def _kwargs_for(fn, kw: dict) -> dict:
    import inspect
    try:
        ps = inspect.signature(fn).parameters
    except (TypeError, ValueError):
        return kw
    if any(p.kind == p.VAR_KEYWORD for p in ps.values()):
        return kw
    return {k: v for k, v in kw.items() if k in ps}


def family_atoms(S: Src, *, exchange=None, ctx: dict | None = None, families=None) -> list[Mol]:
    """The single-site edits of the existing families (ATOM_FAMILIES, each called with its pure candidates() on the incumbent, the

"""
    ctx = ctx or {}
    allow = ctx.get("t5_family_ops") or {}
    out, seen = [], {S.proof.strip()}
    for fam, mname in ATOM_FAMILIES.items():
        if families is not None and fam not in families:
            continue
        try:
            mod = importlib.import_module(mname)
        except ImportError:
            continue
        al = [o if str(o).startswith(fam + ":") else f"{fam}:{o}" for o in (allow.get(fam) or [])]
        kw = {"exchange": exchange, "max_per_op": ATOM_PER_OP.get(fam, 8)}
        if fam != "sweep":
            sub = {k: ctx[k] for k in ("source", "pins", "compile_s", "profile", "goals", "t4_probe", "t4_probe_for") if k in ctx}
            ops = al
            if fam == "t3":
                ops = [o for o in (al or ATOM_T3_OPS) if o in ATOM_T3_OPS]
                if not ops:
                    continue
            if ops:
                sub["ops"] = list(ops)
            kw["ctx"] = sub
        try:
            raw = mod.candidates(S.proof, S.statement, **_kwargs_for(mod.candidates, kw))
        except Exception:                                                                               
            continue
        for c in raw or []:
            if not isinstance(c, dict):
                continue
            decl = c.get("decl") or c.get("proof")
            op = str(c.get("op") or fam)
            fop = op if op.startswith(fam + ":") or op == fam else f"{fam}:{op}"
            if not isinstance(decl, str) or decl.strip() in seen or (al and fop not in al):
                continue
            if c.get("cost") == "expensive":
                continue
            seen.add(decl.strip())
            m = S.mol(diff_edits(S.proof, decl.strip() if S.proof == S.proof.strip() else decl), "single", fop,
                      note=str(c.get("note") or "")[:80])
            if m is None:
                continue
            dt = S.dtok(m.edits)
            if dt is None or dt < 1:
                continue
            out.append(m)
    return out


                                                                                                                                    
_NAMED = re.compile(r"\(\s*(" + NAME + r")\s*:=")
_CONFIG_PRE = re.compile(r"^\s*(?:[·.]\s+)?[\w'!?]+(?:\s+(?:\(\s*[\w.]+\s*:=[^()]*\)|[+-][\w.]+))*\s*$")


def _named_args(S: Src) -> list[Mol]:
    """Every named argument `(x := e)` of an application, deleted with its leading blanks (not a tactic's configuration item). One that

"""
    out = []
    for i, j in sorted(S.pairs.items()):
        if i < S.off0 or S.code[i] != "(" or not _NAMED.match(S.code, i):
            continue
        if S.code[i:j].count(":=") < 1:
            continue
        ls = S.line_start(i)
        pre = S.code[ls:i]
        tail = re.split(r"<;>|;|=>|:=|\bby\b|·", pre)[-1]
        what = S.proof[i:j + 1]
        prev = S.code[S.line_start(ls - 1):ls - 1] if ls > S.off0 else ""
        if _CONFIG_PRE.match(tail) or _CONFIG_PRE.match(pre) or (not pre.strip() and prev.strip() and _CONFIG_PRE.match(prev)):
            _why("t5:elide", S, i, what, "named: a tactic's configuration item")
            continue
        a = i
        while a > ls and S.proof[a - 1] in _BLANK:
            a -= 1
        if a == i and a != ls:
            _why("t5:elide", S, i, what, "named: no blank before it")
            continue
        if a == ls:                    
            e = j + 1
            while e < len(S.proof) and S.proof[e] in _BLANK:
                e += 1
            if e >= len(S.proof) or S.proof[e] == "\n":
                if ls - 1 < S.off0:
                    continue
                ed = Edit(ls - 1, e, "")
            else:
                ed = Edit(i, e, "")
        else:
            ed = Edit(a, j + 1, "")
        m = S.mol([ed], "t5:elide", "elide/named", note=f"L{S.line(i) + 1}", groups=(f"named@{i}",))
        if m:
            out.append(m)
    return out


def _ascriptions(S: Src) -> list[Mol]:
    """Type ascriptions `(e : T)` of terms -> `e` (bare where it stands as a whole term, else `(e)`), and the types of fun /
"""
    out = []
    for i, j in sorted(S.pairs.items()):
        if i < S.off0 or S.code[i] != "(":
            continue
        cs = [p for p in _depth0(S, i + 1, j, ":") if S.code[p + 1:p + 2] not in ("=", ":") and S.code[p - 1:p] != ":"]
        if not cs or _depth0(S, i + 1, j, ":=") or _depth0(S, i + 1, j, ","):
            continue
        p = cs[0]
        e_txt, t_txt = S.proof[i + 1:p].strip(), S.proof[p + 1:j].strip()
        if not e_txt or not t_txt or "|" in S.code[i + 1:p]:
            continue
        kind = _binder_ctx(S, i)
        if kind == "header":
            _why("t5:elide", S, i, S.proof[i:j + 1], "ascription: a have / let / pattern header's binder")
            continue
        if kind == "binder":
            if not re.fullmatch(r"(?:(?:" + NAME + r"|_)\s+)*(?:" + NAME + r"|_)", e_txt):
                _why("t5:elide", S, i, S.proof[i:j + 1], "ascription: binder group with a non-name")
                continue
            m = S.mol([Edit(i, j + 1, e_txt)], "t5:elide", "elide/binder", note=f"L{S.line(i) + 1}", groups=(f"ascr@{i}",))
        else:
            if e_txt.startswith(("←", "by ", "fun ", "λ")):
                _why("t5:elide", S, i, S.proof[i:j + 1], "ascription: the term starts with ← / by / fun")
                continue
            m = S.mol([Edit(i, j + 1, _wrap(S, i, j + 1, e_txt))], "t5:elide", "elide/ascription", note=f"L{S.line(i) + 1}",
                      groups=(f"ascr@{i}",))
        if m:
            out.append(m)
    return out


_BINDER_TY = re.compile(r"(?<![" + _IDC + r".])(fun|λ|∀|∃!?)[ \t]*((?:(?:" + NAME + r"|_)[ \t]+)*(?:" + NAME + r"|_))[ \t]*:(?![=:])")


def _binder_types(S: Src) -> list[Mol]:
    """Unparenthesized binder types: `fun x y : T =>` / `λx : T =>` -> `fun x y =>`, `∀ x : T,` / `∃ x : T,` -> `∀ x,` (the type runs
"""
    out = []
    for mm in _BINDER_TY.finditer(S.code):
        p = mm.start()
        if p < S.off0:
            continue
        stop = "=>" if mm.group(1) in ("fun", "λ") else ","
        d = S.depth[p]
        k, hit = mm.end(), None
        while k < len(S.code):
            if S.depth[k] < d:
                break
            if S.depth[k] == d and S.code.startswith(stop, k):
                hit = k
                break
            k += 1
        what = S.proof[p:min(len(S.proof), mm.end() + 24)]
        if hit is None:
            _why("t5:elide", S, p, what, f"binder type: no `{stop}` at the binder's depth")
            continue
        ne = mm.start(2) + len(mm.group(2))
        m = S.mol([Edit(ne, hit, " ")], "t5:elide", "elide/binder", note=f"L{S.line(p) + 1}", groups=(f"ascr@{mm.start(2)}",))
        if m:
            out.append(m)
    return out


def _step_list(S: Src) -> list:
    """Every step of T3's tactic tree (cached on S), in source order."""
    got = getattr(S, "_steps_cache", None)
    if got is None:
        got = [st for _, _, st in _steps(S)]
        S._steps_cache = got
    return got


def _step_at(S: Src, pos: int):
    """The innermost tactic step holding the offset `pos` (None: none, or no tree)."""
    best = None
    for st in _step_list(S):
        if st.start <= pos < max(st.end, st.start + 1) and (best is None or st.end - st.start < best.end - best.start):
            best = st
    return best


_HAVE_HEAD = re.compile(r"(have|let|obtain)\s+")


def _have_types(S: Src) -> list[Mol]:
    """`have h : T := v` / `let x : T := v` / `obtain pat : T := v` with a term value (not `by`) -> the same without `: T`. The header
"""
    out = []
    for li in range(S.line(S.off0), len(S.line0)):
        ls = S.line0[li]
        le = S.line_end(ls)
        if ls < S.off0:
            continue
        line = S.code[ls:le]
        m = re.match(r"\s*(?:[·.]\s+)?", line)
        k = ls + m.end()
        mh = _HAVE_HEAD.match(S.code, k)
        if not mh:
            continue
        p = mh.end()
        if S.code[p:p + 1] == "⟨" and p in S.pairs:
            p = S.pairs[p] + 1
        else:
            mn = re.match(NAME, S.code[p:])
            if mn:
                p += mn.end()
        while p < le and S.code[p] in _BLANK:
            p += 1
        if S.code[p:p + 1] != ":" or S.code[p:p + 2] == ":=":
            continue
        st = _step_at(S, k)
        lim = max(le, st.end) if st is not None and st.start == k else le
        asg = _depth0(S, p, lim, ":=")
        if not asg:
            _why("t5:elide", S, k, S.proof[k:le], "have-type: no `:=` in the step")
            continue
        q = asg[0]
        val = S.code[q + 2:lim].strip()
        if not val or re.match(r"by\b", val):
            _why("t5:elide", S, k, S.proof[k:le], "have-type: a `by` value (its type is the goal)" if val else "have-type: no value")
            continue
        s0 = p
        while s0 > ls and S.proof[s0 - 1] in _BLANK:
            s0 -= 1
        mo = S.mol([Edit(s0, q, " ")], "t5:elide", "elide/have-type", note=f"L{li + 1}", groups=(f"htype@{ls}",))
        if mo:
            out.append(mo)
    return out


def _steps(S: Src):
    """(block, index, step) of T3's tactic tree, in source order."""
    if not S.tree:
        return
    _, top = S.tree
    for blk in T3._blocks(top):
        for i, st in enumerate(blk.steps):
            yield blk, i, st


def _step_text(S: Src, st) -> str:
    return S.proof[st.start:st.end]


def _own_line(S: Src, st) -> bool:
    """The step starts its line (only indentation before it) and nothing follows it on its last line."""
    ls = S.line_start(st.start)
    return not S.code[ls:st.start].strip() and not S.code[st.end:S.line_end(st.end)].strip()


def _del_lines(S: Src, st) -> Edit:
    a = S.line_start(st.start)
    e = S.line_end(st.end)
    return Edit(a, min(e + 1, len(S.proof)), "") if e < len(S.proof) else Edit(max(S.off0, a - 1), e, "")


def _shows(S: Src) -> list[Mol]:
    """A `show T` / `change T` step (no `from` / `by`) deleted; a term `show T from e` -> `e`, `show T by tac` -> `by tac` (the `from` /
"""
    out = []
    for blk, i, st in _steps(S):
        t = S.code[st.start:st.end]
        if re.match(r"(show|change)\s", t) and len(blk.steps) > 1 and _own_line(S, st) and not st.children \
                and not _depth0(S, st.start, st.end, "from") and not re.search(r"\bby\b", t):
            m = S.mol([_del_lines(S, st)], "t5:elide", "elide/show-step", note=f"L{st.l0 + 1}", groups=(f"show@{st.start}",))
            if m:
                out.append(m)
        elif re.match(r"(show|change)\s", t):
            _why("t5:elide", S, st.start, t, "show-step: the block's only step" if len(blk.steps) <= 1 else
                 "show-step: not on its own line" if not _own_line(S, st) else "show-step: has a nested block" if st.children else
                 "show-step: holds from / by")
    for mm in re.finditer(r"(?<![\w'.])show\s", S.code):
        p = mm.start()
        if p < S.off0:
            continue
        ls = S.line_start(p)
        if not S.code[ls:p].strip():
            continue                                  
        st = _step_at(S, p)
        lim = st.end if st is not None else S.line_end(p)
        hit = None
        for k in range(mm.end(), lim):
            if S.depth[k] < S.depth[p]:
                break
            if S.depth[k] == S.depth[p] and re.match(r"(?<![\w'])(from|by)(?![\w'])", S.code[k:k + 5]) \
                    and not re.match(r"[\w']", S.code[k - 1]):
                hit = k
                break
        if hit is None:
            _why("t5:elide", S, p, S.proof[p:S.line_end(p)], "show-term: no from / by at its depth")
            continue
        if S.code.startswith("from", hit):
            e = hit + 4
            while e < len(S.proof) and S.proof[e] in _BLANK + "\n":
                e += 1
            m = S.mol([Edit(p, e, "")], "t5:elide", "elide/show-from", note=f"L{S.line(p) + 1}", groups=(f"show@{p}",))
        else:
            m = S.mol([Edit(p, hit, "")], "t5:elide", "elide/show-by", note=f"L{S.line(p) + 1}", groups=(f"show@{p}",))
        if m:
            out.append(m)
    return out


_LIST_HEADS = r"(?:simp_all|simp_rw|simp|dsimp|simpa|field_simp|norm_num|unfold|delta)"


def _list_use(S: Src, u: int, name: str):
    """A use of a let / have name at u that only unfolds it: a whole item of a simp-set list (`simp only [.., x, ..]`, dsimp, simp_all,

"""
    st = _step_at(S, u)
    best = None
    for o, c in S.pairs.items():
        if S.code[o] == "[" and o < u < c and (best is None or o > best[0]):
            best = (o, c)
    if best is not None:
        o, c = best
        if st is None or not re.match(_LIST_HEADS + r"(?![\w'!?])", S.code[st.start:o]):
            return None
        items = _item_spans(S, o, c)
        for idx, (a, e, _) in enumerate(items):
            if a == u and e == u + len(name):
                if len(items) > 1:
                    return [Edit(a, items[idx + 1][0], "")] if idx + 1 < len(items) else [Edit(items[idx - 1][1], e, "")]
                rest = (S.code[st.start:o] + S.code[c + 1:st.end]).split()
                if len(rest) <= 2 and not st.children and _own_line(S, st):                                                
                    return [_del_lines(S, st)]
                a0 = o
                while a0 > st.start and S.proof[a0 - 1] in _BLANK:
                    a0 -= 1
                return [Edit(a0, c + 1, "")]
        return None
    if st is not None and re.match(r"(?:unfold|delta)\s", S.code[st.start:st.end]) and st.l0 == st.l1:
        words = S.code[st.start:st.end].split()
        if name in words[1:] and "at" not in words:
            if len(words) == 2 and _own_line(S, st):
                return [_del_lines(S, st)]
            a = u
            while a > st.start and S.proof[a - 1] in _BLANK:
                a -= 1
            return [Edit(a, u + len(name), "")]
    return None


_HAVE_STEP = re.compile(r"(have|let)\s+(?:(" + NAME + r")\s*)?(?::\s*(.+?)\s*)?:=\s*(.+)$")


def _rebound(scope: str, name: str) -> bool:
    """Is `name` bound again in the scope text (a binder, a pattern, an intro, a have / let name, an arm pattern)?"""
    w = re.escape(name)
    pats = [r"(?<![\w'])(?:have|haveI|let|letI|set|obtain|intro|intros|rintro|generalize|rename_i)\b[^\n:=]*?(?<![\w'.])" + w
            + r"(?![\w'])",
            r"(?<![\w'])(?:fun|λ|∀|∃!?)\s[^\n=,]*?(?<![\w'.])" + w + r"(?![\w'])[^\n=,]*(?:=>|,)",
            r"(?<![\w'])with\b[^\n]*?(?<![\w'.])" + w + r"(?![\w'])",
            r"(?m)^\s*(?:\||case\b|next\b)[^\n]*?(?<![\w'.])" + w + r"(?![\w'])[^\n]*=>"]
    return any(re.search(p, scope) for p in pats)


def _inlines(S: Src) -> list[Mol]:
    """A tactic `have h := v` / `have h : T := v` / `let x := v` (also `have := v`, name `this`) inlined at EVERY use in the rest of its



"""
    out = []
    for blk, i, st in _steps(S):
        t = S.code[st.start:st.end]
        if not re.match(r"(have|let)\s", t):
            continue
        if i + 1 >= len(blk.steps) or not _own_line(S, st):
            _why("t5:elide", S, st.start, t, "inline: the block's last step" if i + 1 >= len(blk.steps) else "inline: not on its own line")
            continue
        m = _HAVE_STEP.match(" ".join(t.split()))
        if not m:
            _why("t5:elide", S, st.start, t, "inline: header with binders or a pattern")
            continue
        kw, name, ty = m.group(1), m.group(2) or "this", m.group(3)
        if kw == "let" and name == "this":
            continue
        asg = _depth0(S, st.start, st.end, ":=")
        if not asg:
            continue
        if any(not c.inline or len({s.l0 for s in c.steps}) > 1 for c in st.children) or re.search(r"\bby[ \t]*\n", S.code[asg[0]:st.end]):
            _why("t5:elide", S, st.start, t, "inline: the value holds a tactic block over several lines")
            continue
        val = " ".join(S.proof[asg[0] + 2:st.end].split())
        if not val or (ty and _depth0(S, st.start, asg[0], ":") == []):
            continue
        ty = " ".join(ty.split()) if ty else ty
        a0, e0 = blk.steps[i + 1].start, blk.steps[-1].end
        scope = S.code[a0:e0]
        if _rebound(scope, name) or (name == "this" and re.search(r"(?<![\w'])(?:have|suffices)\s*:", scope)):
            _why("t5:elide", S, st.start, t, "inline: the name is bound again in its scope")
            continue
        uses = [a0 + u.start() for u in _word_re(name).finditer(scope)]
        if not uses:
            _why("t5:elide", S, st.start, t, "inline: no use in its block (outside the block, or unused)")
            continue
        for variant in (("plain", None), ("typed", ty)):
            if variant[0] == "typed" and not ty:
                continue
            eds = [_del_lines(S, st)]
            for u in uses:
                e = u + len(name)
                lu = _list_use(S, u, name)
                if lu is not None:
                    eds += lu
                elif variant[0] == "typed":
                    eds.append(Edit(u, e, f"({val} : {ty.strip()})"))
                else:
                    eds.append(Edit(u, e, _wrap(S, u, e, val if not val.startswith("by ") else f"({val})")))
            mo = S.mol(list(dict.fromkeys(eds)), "t5:elide", f"elide/inline-{variant[0]}", note=f"{name} x{len(uses)} L{st.l0 + 1}",
                       groups=(f"inline@{st.start}",))
            if mo:
                out.append(mo)
    return out


def elide_atoms(S: Src) -> list[Mol]:
    """D3: every elision atom of the proof (named arguments, type ascriptions and binder types, have / let / obtain types, show and
"""
    out, seen = [], {S.proof}
    for m in _named_args(S) + _ascriptions(S) + _binder_types(S) + _have_types(S) + _shows(S) + _inlines(S):
        d = S.decl(m.edits)
        if d in seen:
            continue
        dt = S.dtok(m.edits)
        if dt is None or dt < 1:
            _why("t5:elide", S, m.edits[0].a, m.label(), f"{m.src.split('/')[-1]}: saves no token")
            continue
        seen.add(d)
        out.append(m)
    return out


def class_unions(S: Src, atoms: list[Mol]) -> list[Mol]:
    """D3's joint form: per elision class (named / ascription and binder / have-type / show / inline) the union of every compatible
"""
    by: dict = {}
    for m in atoms:
        cls = m.src.split("/")[1].split("-")[0] if "/" in m.src else m.src
        cls = "ascription" if cls == "binder" else cls
        by.setdefault(cls, []).append(m)
    out = []

    def greedy(ms, label):
        acc: list = []
        for m in sorted(ms, key=lambda x: x.edits[0].a):
            if all(compatible(m, x) for x in acc):
                acc.append(m)
        if len(acc) >= 2:
            u = union(acc, op="t5:elide")
            if u is not None:
                u.src, u.note = f"elide/all-{label}", f"{len(acc)} sites"
                u.kind = "alt"
                out.append(u)
    for cls, ms in sorted(by.items()):
        greedy(ms, cls)
        if len(ms) >= 4:
            ms2 = sorted(ms, key=lambda x: x.edits[0].a)
            h = len(ms2) // 2
            greedy(ms2[:h], cls + "-1")
            greedy(ms2[h:], cls + "-2")
    if len(by) >= 2:
        greedy(atoms, "classes")
    return out


                                                                                                                                       
_LISTCALL = re.compile(r"^(simp_all|simp|dsimp|simpa|rw|rewrite)(\s+only)?\s*(?:\[(.*)\])?\s*$", re.S)


def split_items(inner: str) -> list[str]:
    """The items of a bracketed list's inner text, split at its depth-0 commas (stripped, empty ones dropped)."""
    m = _mask(inner)
    d, cur, out = 0, [], []
    for i, ch in enumerate(inner):
        if not m[i]:
            if ch in "([{⟨":
                d += 1
            elif ch in ")]}⟩":
                d -= 1
            elif ch == "," and d == 0:
                out.append("".join(cur).strip())
                cur = []
                continue
        cur.append(ch)
    out.append("".join(cur).strip())
    return [x for x in out if x]


def _norm(t: str) -> str:
    return " ".join(t.split())


def _union_simp(bodies: list[str]) -> list[tuple[str, str]]:
    """One simp call holding every lemma of the bodies' simp / rw calls (the proof's own vocabulary): `simp only [U]` when every call
"""
    heads, items = [], []
    for b in bodies:
        m = _LISTCALL.match(_norm(b))
        if not m:
            return []
        heads.append((m.group(1), bool(m.group(2))))
        for it in split_items(m.group(3) or ""):
            if _norm(it) not in [_norm(x) for x in items]:
                items.append(it)
    if any(h == "simpa" for h, _ in heads):
        return []
    lst = f" [{', '.join(items)}]" if items else ""
    out = []
    if all(o or h in ("rw", "rewrite") for h, o in heads) and items:
        out.append((f"simp only{lst}", "union-only"))
    out.append((f"simp{lst}", "union"))
    if any(h == "simp_all" for h, _ in heads):
        out.append((f"simp_all{lst}", "union-all"))
    return out


def _anon_ctor(bodies: list[str]) -> list[tuple[str, str]]:
    """`exact ⟨c1, .., ck⟩` in every body with the same arity: the components that agree kept, the others `‹_›` (an assumption of
"""
    comps = []
    for b in bodies:
        m = re.fullmatch(r"exact\s+⟨(.*)⟩", _norm(b))
        if not m:
            return []
        comps.append(split_items(m.group(1)))
    k = len(comps[0])
    if k < 2 or any(len(c) != k for c in comps):
        return []
    same = [len({_norm(c[i]) for c in comps}) == 1 for i in range(k)]
    if all(same):
        return []
    v1 = [comps[0][i] if same[i] else "‹_›" for i in range(k)]
    first = same.index(False)
    v2 = [comps[0][i] if same[i] else ("_" if i == first else "‹_›") for i in range(k)]
    return [(f"exact ⟨{', '.join(v)}⟩", "anon") for v in (v1, v2)]


def _alt_text(lines: list[str]) -> str | None:
    """A body as one alternative of `first | ..`: a one-line body as it is (parenthesized when it holds `|`), a flat multi-line body
"""
    ls = [l.rstrip() for l in lines if l.strip()]
    if not ls:
        return None
    if len(ls) == 1:
        t = _norm(ls[0])
        return f"({t})" if "|" in t else t
    if any(l[:1] in (" ", "\t") for l in ls) or any(re.search(r"(\bby|=>|\bwith|·)\s*$", l) for l in ls):
        return None
    return "(" + "; ".join(_norm(l) for l in ls) + ")"


def closers(S: Src, bodies: list[list[str]], *, own_vocab_only: bool = False, ctx: dict | None = None) -> list[dict]:
    """Shared closers for the goals the bodies close (each body a list of lines): {"lines", "src", "expensive"}, fewest tokens first



"""
    flat = ["\n".join(b) for b in bodies]
    norm = [_norm(f) for f in flat]
    one = all(len([l for l in b if l.strip()]) == 1 for b in bodies)
    out: list = []

    def add(lines, src, exp=False):
        key = _norm("\n".join(lines))
        if key and all(_norm("\n".join(o["lines"])) != key for o in out):
            out.append({"lines": list(lines), "src": src, "expensive": exp})
    if len(set(norm)) == 1:
        add([l for l in bodies[0]] if not one else [norm[0]], "same")
    if one:
        for t, src in _union_simp(norm):
            add([t], src)
        for t, src in _anon_ctor(norm):
            add([t], src)
    seen_n, alts = set(), []
    for i in range(len(bodies)):
        if norm[i] in seen_n:
            continue
        seen_n.add(norm[i])
        alts.append(_alt_text(bodies[i]))
    if 2 <= len(alts) <= FIRST_MAX and all(a is not None for a in alts) and "first" in HEADS:
        add(["first | " + " | ".join(alts)], "first")
    if len(alts) >= 2:
        for i in range(len(bodies)):
            ls = [l for l in bodies[i] if l.strip()]
            if ls:
                add([norm[i]] if len(ls) == 1 else list(bodies[i]), "body")
    if own_vocab_only or not S.tree:
        return out
    doc, top = S.tree
    own = T3._own_terminals(doc, top)
    scope = T3._scope(S.proof, ctx)
    try:
        d1, _ = T3._closer_lists(own, scope)
    except Exception:                
        d1 = []
    n_own = n_cheap = n_exp = 0
    for c in d1:
        if c.get("own"):
            if n_own < CLOSERS_OWN:
                n_own += 1
                add([c["text"]], "own")
        elif c.get("cost") == "cheap":
            if n_cheap < CLOSERS_TABLE:
                n_cheap += 1
                add([c["text"]], "table")
        elif c.get("cost") == "expensive" and n_exp < CLOSERS_EXPENSIVE:
            n_exp += 1
            add([c["text"]], "table-expensive", True)
    return out


def _bullet_body(S: Src, st) -> list[str] | None:
    """A bullet step's body as lines (the first line's text after `·`, the later lines dedented to its column), or None."""
    if any(S.mask[st.start:st.end]):
        return None
    t = S.proof[st.start:st.end]
    m = re.match(r"[·.][ \t]+", t)
    if not m:
        return None
    col = (st.start - S.line_start(st.start)) + m.end()
    lines = t[m.end():].split("\n")
    out = [lines[0].rstrip()]
    for l in lines[1:]:
        if l.strip() and len(l) - len(l.lstrip(" ")) < col:
            return None
        out.append(l[col:].rstrip() if l.strip() else "")
    return out


def _is_bullet(S: Src, st) -> bool:
    return bool(re.match(r"[·.][ \t]", S.code[st.start:st.start + 2]))


def _block_text(lines: list[str], col: int) -> str:
    return "\n".join((" " * col + l) if l.strip() else "" for l in lines)


def _goal_all(S: Src, a: int, e: int, col: int, c: dict) -> Edit | None:
    """[a, e) replaced by `all_goals C` (one line), or `all_goals` + C's lines as an indented block."""
    if "all_goals" not in HEADS:
        return None
    ls = c["lines"]
    if len(ls) == 1:
        return Edit(a, e, "all_goals " + ls[0].strip())
    return Edit(a, e, "all_goals\n" + _block_text(ls, col + 2))


def _nameless(S: Src, mol: Mol, lo: int, hi: int, ctx: dict | None) -> list[Mol]:
    """Nameless follow-ups of a shared-closer variant: on the variant's text, T4's bare forms and T2's unused-name intros whose edit
"""
    V = S.decl(mol.edits)
    out = []
    for fam, ops in (("t4", ["t4:rcases", "t4:induction"]), ("t2", ["t2:intros"])):
        try:
            mod = importlib.import_module(ATOM_FAMILIES[fam])
            raw = mod.candidates(V, S.statement, max_per_op=4, ctx={"ops": ops, **{k: (ctx or {})[k] for k in ("source",) if k in (ctx or {})}})
        except Exception:                
            continue
        for c in raw or []:
            d = c.get("decl")
            if not isinstance(d, str) or str(c.get("op")) not in ops:
                continue
            e2 = diff_edits(V, d)
            if not e2:
                continue
            ok = True
            for x in e2:
                b = to_base(mol.edits, x.a)
                if not (lo <= S.line(b) <= hi):
                    ok = False
            if not ok:
                continue
            m = S.mol(diff_edits(S.proof, d), mol.op, mol.src + "+nameless", note=f"{mol.note}; {c.get('op')}", groups=mol.groups,
                      kind="alt", expensive=mol.expensive)
            if m:
                out.append(m)
    return out


def _arms(S: Src, st):
    """(head text up to `with`, [arm]) of a step `head with` + `| pattern => body` alternatives, or None. arm: {"ls" line start, "bar"
"""
    first_end = S.line_end(st.start)
    mw = re.search(r"\bwith\s*$", S.code[st.start:first_end])
    if not mw or st.l1 == st.l0 or any(S.mask[st.start:st.end]):
        return None
    head = S.proof[st.start:st.start + mw.start()].rstrip()
    rows = []
    for li in range(st.l0 + 1, st.l1 + 1):
        ls = S.line0[li]
        le = S.line_end(ls)
        t = S.code[ls:le]
        if t.lstrip().startswith("|"):
            rows.append((li, ls, ls + len(t) - len(t.lstrip()), len(t) - len(t.lstrip())))
    if len(rows) < 2:
        return None
    ind = rows[0][3]
    rows = [r for r in rows if r[3] == ind]
    arms = []
    for k, (li, ls, bar, _) in enumerate(rows):
        le = S.line_end(ls)
        ar = _depth0(S, bar, le, "=>")
        if not ar:
            return None
        end = (rows[k + 1][1] - 1) if k + 1 < len(rows) else st.end
        body = S.proof[ar[0] + 2:end]
        lines = [l for l in body.split("\n")]
        arms.append({"ls": ls, "bar": bar, "pat": S.proof[bar + 1:ar[0]].strip(), "arrow": ar[0] + 2, "end": end,
                     "body": [lines[0].strip()] + [l.strip() for l in lines[1:]], "norm": _norm(body)})
    return head, arms


def _unit_kind(S: Src, st) -> str | None:
    """A step that closes goals on its own: "bullet" (`· tacs`), "case" (`case tag .. => tacs`, `next .. => tacs`: one goal each),
"""
    t = S.code[st.start:st.start + 12]
    if re.match(r"[·.][ \t]", t):
        return "bullet"
    if re.match(r"(?:case|next)(?![\w'!?])", t):
        return "case"
    if re.match(r"(?:all_goals|any_goals)(?![\w'!?])", t):
        return "all"
    return None


def _unit_body(S: Src, st, kind: str) -> list[str] | None:
    """A unit's body as lines (dedented), or None (a comment or string inside, an under-indented line, no `=>`)."""
    if kind == "bullet":
        return _bullet_body(S, st)
    if any(S.mask[st.start:st.end]):
        return None
    le = S.line_end(st.start)
    if kind == "case":
        ar = _depth0(S, st.start, le, "=>")
        if not ar:
            return None
        p = ar[0] + 2
    else:
        p = st.start + len(re.match(r"(?:all_goals|any_goals)", S.code[st.start:]).group(0))
    first = S.proof[p:le].strip()
    rest = S.proof[le + 1:st.end].split("\n") if st.l1 > st.l0 else []
    lines = [first] if first else []
    if rest:
        if first:
            col = (p - S.line_start(p)) + (len(S.proof[p:le]) - len(S.proof[p:le].lstrip()))
        else:
            nb = [l for l in rest if l.strip()]
            col = min(len(l) - len(l.lstrip(" ")) for l in nb) if nb else 0
        for l in rest:
            if l.strip() and len(l) - len(l.lstrip(" ")) < col:
                return None
            lines.append(l[col:].rstrip() if l.strip() else "")
    return lines if [l for l in lines if l.strip()] else None


def shared_sites(S: Src, ctx: dict | None = None) -> list[Mol]:
    """D1 (op t5:shared) and D4 (op t5:collapse) site variants, SITE_MAX per site, fewest tokens first:







"""
    out: list = []
    if not S.tree:
        _why("t5:shared", S, None, "", "no tactic tree (term mode or a layout the parser does not read)")
        return out

    def keep(cands, site, lo=None, hi=None):
        ms = []
        for op, src, eds, note, exp in cands:
            if any(e is None for e in eds) or any(any(S.mask[e.a:e.e]) for e in eds):
                continue                                                                      
            m = S.mol(eds, op, src, note=note, groups=(site,), kind="alt", expensive=exp)
            if m is None:
                continue
            dt = S.dtok(m.edits)
            if dt is None or dt < 1:
                continue
            ms.append((-dt, len(ms), m))
        if cands and not ms:
            _why(cands[0][0], S, int(site.split("@")[1]) if "@" in site else None, site, "every variant at the site costs tokens")
        ms.sort(key=lambda x: x[:2])
        kept = [m for _, _, m in ms[:SITE_MAX]]
        if lo is not None:
            extra = []
            for m in kept[:3]:
                extra += _nameless(S, m, lo, hi, ctx)
            kept += [m for m in extra if (S.dtok(m.edits) or 0) >= 1][:SITE_MAX]
        out.extend(kept)
    for blk in T3._blocks(S.tree[1]):
        steps = blk.steps
        n = len(steps)
        kinds = [_unit_kind(S, st) for st in steps]
        r = n
        if r > 0 and kinds[r - 1] == "all":
            r -= 1
        while r > 0 and kinds[r - 1] in ("bullet", "case"):
            r -= 1
        k = n - r
        rest = []                                                                                                      
        if k <= 1:
            q = n - 1 if n and kinds[n - 1] == "all" else n
            while q > 0 and kinds[q - 1] is None and steps[q - 1].l0 == steps[q - 1].l1 and _own_line(S, steps[q - 1]) \
                    and not any(S.mask[steps[q - 1].start:steps[q - 1].end]) and all(c.inline for c in steps[q - 1].children):
                q -= 1
            r2 = q
            while r2 > 0 and kinds[r2 - 1] in ("bullet", "case"):
                r2 -= 1
            if q - r2 >= 2 and q < n:
                r, k = r2, n - r2
                rest = list(range(q, n))
        nb = sum(1 for kd in kinds[:r] if kd in ("bullet", "case"))
        if nb >= 1:
            _why("t5:shared", S, steps[0].start, f"{nb} unit(s) before the block's end", "units not at the end of their block")
        if k == 1:
            _why("t5:shared", S, steps[r].start, "one trailing unit", "one unit (needs >= 2)")
        if k >= 2:
            if rest:
                bodies = [_unit_body(S, st, kd) for st, kd in zip(steps[r:rest[0]], kinds[r:rest[0]])]
                tail = []
                for j in rest:
                    if kinds[j] is None:
                        tail.append(_norm(S.proof[steps[j].start:steps[j].end]))
                    else:
                        ub = [_norm(l) for l in (_unit_body(S, steps[j], "all") or []) if l.strip()]
                        tail.append("all_goals " + (ub[0] if len(ub) == 1 else "(" + "; ".join(ub) + ")"))
                bodies.append(tail)
            else:
                bodies = [_unit_body(S, st, kd) for st, kd in zip(steps[r:], kinds[r:])]
            if not (all(b is not None for b in bodies) and _own_line(S, steps[r])):
                _why("t5:shared", S, steps[r].start, f"{k} units", "a unit's body holds a comment / string or an under-indented line"
                     if not all(b is not None for b in bodies) else "the first unit is not on its own line")
            else:
                col = steps[r].start - S.line_start(steps[r].start)
                a, e = steps[r].start, steps[n - 1].end
                cands = []
                what = "+".join(sorted({kd for kd in kinds[r:] if kd})) + ("+rest" if rest else "")
                sp = steps[r - 1] if r >= 1 else None
                sp_ok = sp is not None and not sp.children and kinds[r - 1] is None and _own_line(S, sp) \
                    and not re.match(r"case'", S.code[sp.start:sp.end]) and not any(S.mask[sp.start:sp.end])
                for c in closers(S, bodies, ctx=ctx):
                    cands.append(("t5:shared", f"shared/all_goals-{c['src']}", [_goal_all(S, a, e, col, c)], f"{k} units ({what})",
                                  c["expensive"]))
                    if sp_ok and len(c["lines"]) == 1:
                        cands.append(("t5:shared", f"shared/then-{c['src']}", [Edit(sp.end, e, " <;> " + c["lines"][0].strip())],
                                      f"{k} units ({what})", c["expensive"]))
                if not cands:
                    _why("t5:shared", S, a, f"{k} units", "no shared closer for the units")
                lo = steps[r - 1].l0 if r >= 1 else steps[r].l0
                keep(cands, f"units@{a}", lo=max(lo - 1, S.line(S.off0)), hi=steps[r - 1].l1 if r >= 1 else lo)
                for m_ in range(r + 1, rest[0] if rest else n - 1):
                    sub = bodies[m_ - r:]
                    a2 = steps[m_].start
                    cands = [("t5:collapse", f"collapse/units-{c['src']}", [_goal_all(S, a2, e, col, c)], f"last {n - m_} units",
                              c["expensive"]) for c in closers(S, sub, own_vocab_only=True)]
                    keep(cands, f"units@{a}")
                                                                 
        if n >= 2:
            m_ = n
            while m_ > 0 and steps[m_ - 1].l0 == steps[m_ - 1].l1 and not steps[m_ - 1].children and kinds[m_ - 1] is None \
                    and _own_line(S, steps[m_ - 1]) and not any(S.mask[steps[m_ - 1].start:steps[m_ - 1].end]):
                m_ -= 1
            for s0 in range(m_, n - 1):
                if s0 == 0:
                    continue
                texts = [[_norm(S.proof[st.start:st.end])] for st in steps[s0:]]
                col = steps[s0].start - S.line_start(steps[s0].start)
                cs = [c for c in closers(S, texts, own_vocab_only=True) if c["src"] in ("same",) or c["src"].startswith("union")]
                if cs:
                    keep([("t5:collapse", f"collapse/steps-{c['src']}", [_goal_all(S, steps[s0].start, steps[n - 1].end, col, c)],
                           f"last {n - s0} steps", c["expensive"]) for c in cs], f"steps@{steps[s0].start}")
    for blk, i, st in _steps(S):
        got = _arms(S, st)
        if not got:
            continue
        head, arms = got
        kind = head.split()[0] if head.split() else ""
        cands = []
        if kind != "match" and all(a["body"][0] for a in arms):                                                                  
            for c in closers(S, [a["body"] for a in arms], ctx=ctx):
                if len(c["lines"]) == 1:
                    cands.append(("t5:shared", f"shared/arms-{c['src']}", [Edit(st.start, st.end, head + " <;> " + c["lines"][0].strip())],
                                  f"{len(arms)} alternatives", c["expensive"]))
        for m_ in range(0, len(arms) - 1):
            tail = arms[m_:]
            if len(tail) < 2 or len({a["norm"] for a in tail}) != 1:
                continue
            a0 = tail[0]
            if kind == "match":
                ar = len(split_items(a0["pat"]))
                wild = ", ".join(["_"] * ar)
            else:
                wild = "_"
            rep = S.proof[a0["ls"]:a0["bar"]] + "| " + wild + " =>" + S.proof[a0["arrow"]:a0["end"]]
            cands.append(("t5:collapse", "collapse/arms-wildcard", [Edit(a0["ls"], st.end, rep)], f"last {len(tail)} alternatives", False))
        keep(cands, f"arms@{st.start}")
    return out


                                                                                                                                  
