class Site:
    """One rewritable introduction. kind: intro | rcases | induction. li / end: its lines [li, end) of the body. col: its tactic column.
"""

    def __init__(self, kind, li, end, lead, names, forms, **kw):
        self.kind, self.li, self.end, self.lead, self.names, self.forms = kind, li, end, lead, list(names), list(forms)
        self.col = len(lead)
        self.op = "t4:" + kind
        self.key = f"{kind}@{li}"
        self.head = kw.get("head")
        self.alts = kw.get("alts") or []                                                                
        self.goals = kw.get("goals", 1)                                                     
        self.units: list = []                                                                             
        self.used: set = set()
        self.inside = False


def _pattern_kind(pat: str):
    """("flat", names) | ("alt", names) | None for an rcases pattern."""
    p = pat.strip()
    if T2._wrapped(p):
        p = p[1:-1].strip()
    if _FLAT.fullmatch(p):
        names = [x.strip() for x in p[1:-1].split(",")]
        return ("flat", names) if not NOT_NAMES & set(names) else None
    marks = T2._scan0(p)
    if marks and all(m == "|" for _, m in marks):
        parts = [x.strip() for x in p.split("|")]
        if len(parts) >= 2 and all(_SIMPLE.fullmatch(x) for x in parts) and not NOT_NAMES & set(parts):
            return "alt", parts
    return None


def _term_ok(e: str) -> bool:
    """A one-line term usable as `cases e`: balanced, no depth-0 marker (`:`, `:=`, `;`, `<;>`, `|`, `=>`, by / fun / with ...)."""
    if not e or "--" in e or "/-" in e:
        return False
    return T2._scan0(e) == []


def _site_at(B, li: int):
    """The site starting at body line li (syntax only: no scope check), or None."""
    line = B.lines[li]
    if not B.clean(li) or not B.tactic_line(li):
        return None
    m = IND_LINE.match(line)
    if m:
        return _induction_at(B, li, m)
    if T2._ext(B, li) != li + 1:
        return None
    m = INTRO_LINE.match(line)
    if m:
        rest, head = m.group("rest"), m.group("head")
        if T2._scan0(rest):
            return None
        bs = T2._binders(rest)
        if not bs:
            return None
        if all(_SIMPLE.fullmatch(b) for b in bs):
            if NOT_NAMES & set(bs):
                return None
            forms = [("intros", "intros")] + ([("intro", "intro")] if len(bs) == 1 else [])
            return Site("intro", li, li + 1, m.group("lead"), bs, forms, head=head)
        if head == "intros" or not all(_SIMPLE.fullmatch(b) or _FLAT.fullmatch(b) for b in bs):
            return None
        names = []
        for b in bs:
            names += [x.strip() for x in b[1:-1].split(",")] if b.startswith("⟨") else [b]
        if NOT_NAMES & set(names):
            return None
        form = "rintro " + " ".join("⟨⟩" if b.startswith("⟨") else "_" for b in bs)
        return Site("intro", li, li + 1, m.group("lead"), names, [("rintro", form)], head=head)
    for rx, head in ((OBTAIN_LINE, "obtain"), (RCASES_LINE, "rcases")):
        m = rx.match(line)
        if not m:
            continue
        pk = _pattern_kind(m.group("pat"))
        e = m.group("e").strip()
        if pk is None or not _term_ok(e):
            return None
        kind, names = pk
        forms = [("cases", "cases " + e)]
        if kind == "flat":
            forms.append(("pat", "obtain ⟨⟩ := " + e if head == "obtain" else "rcases " + e + " with ⟨⟩"))
        return Site("rcases", li, li + 1, m.group("lead"), names, forms, head=head, goals=len(names) if kind == "alt" else 1)
    return None


def _induction_at(B, li: int, m):
    rest = m.group("rest")
    if T2._scan0(rest) is None or any(k in (";", "<;>", ":=", "=>", "|", "by", "fun", "with") for _, k in T2._scan0(rest)):
        return None
    c = len(m.group("lead"))
    j, alts, n = li + 1, [], len(B.lines)
    while j < n and B.blank(j):
        j += 1
    a = None
    while j < n:
        if B.blank(j):
            j += 1
            continue
        ind = B.ind(j)
        am = ALT_LINE.match(B.lines[j])
        if a is None:
            if not am or ind < c:
                break
            a = ind
        if ind < a or (ind == a and not am):
            break
        if ind > a or not B.clean(j):
            return None
        names = am.group("names").split()
        if am.group("tag") == "_" or NOT_NAMES & set(names) or len([x for x in names if x != "_"]) != len({x for x in names if x != "_"}):
            return None
        k, last = j + 1, j
        while k < n:
            if not B.blank(k):
                if B.ind(k) <= a:
                    break
                last = k
            k += 1
        inline = bool(am.group("rhs"))
        if inline and last != j:
            return None
        if not inline and last == j:
            return None
        if not inline and not all(B.clean(x) or B.blank(x) for x in range(j + 1, last + 1)):
            return None
        alts.append({"tag": am.group("tag"), "names": names, "li": j, "end": last + 1, "inline": inline})
        j = last + 1
    if not alts or len({x["tag"] for x in alts}) != len(alts):
        return None
    names = [x for al in alts for x in al["names"]]
    form = m.group("head") + " " + rest.strip()
    return Site("induction", li, alts[-1]["end"], m.group("lead"), names, [("ind", form)], head=m.group("head"), alts=alts)


def _regions(B) -> list[tuple[int, int]]:
    """Line ranges [a, b) covered by an `unhygienic` opener (a line whose code ends with the word): its tactic sequence, the lines from

"""
    out = []
    for L in range(len(B.lines)):
        code = B.code(L).rstrip()
        if not OPENER.search(code):
            continue
        j = L + 1
        while j < len(B.lines) and B.blank(j):
            j += 1
        if j >= len(B.lines):
            continue
        s = B.ind(j)
        if s < B.ind(L) or (s == B.ind(L) and code.strip() != WRAP):
            continue
        k, last = j, j
        while k < len(B.lines):
            if not B.blank(k):
                if B.ind(k) < s:
                    break
                last = k
            k += 1
        out.append((L + 1, last + 1))
    return out


def _bullets(B, a: int, b: int, col: int) -> list[tuple[int, int]] | None:
    """The scope [a, b) as consecutive `·` bullets at column col: their line ranges, or None."""
    out, j = [], a
    while j < b:
        if B.blank(j):
            j += 1
            continue
        if B.ind(j) != col or not B.lines[j].lstrip().startswith("·"):
            return None
        e = B.block_end(j, strict=True)
        out.append((j, min(e, b)))
        j = e
    return out


def _span(B, a: int, b: int) -> tuple[int, int]:
    s = B.starts[a]
    e = B.starts[b] if b < len(B.lines) else len(B.body)
    return s, e


def _refs(B, S, s: int, e: int, name: str) -> list[int] | None:
    """Offsets of the uses of `name` in [s, e) outside comments and strings; None when one of them is not a plain reference."""
    rx = re.compile(_ID_L + re.escape(name) + _ID_R)
    hole = re.compile(r"(?<![" + _IDC + r".])\?" + re.escape(name) + _ID_R)                                                       
    if any(not B.mask[h.start()] for h in hole.finditer(B.body, s, e)):
        return None
    out = []
    for mm in rx.finditer(B.body, s, e):
        i = mm.start()
        if B.mask[i]:
            continue
        if S.binds(i):
            return None
        k = i - 1
        while k >= 0 and B.body[k] in " \t":
            k -= 1
        if k >= 0 and B.body[k] == "?":
            return None
        if k >= 0 and B.body[k] == "(" and re.match(r"[ \t]*:=", B.body[mm.end():]):
            return None
        out.append(i)
    return out


def _words(B, s: int, e: int) -> set:
    return {mm.group(0) for mm in re.finditer(r"[^\W\d][" + _IDC + r"]*", B.body[s:e])}


def _scopes(B, S, site: Site) -> bool:
    """Fill site.units ([{"id", "s", "e", "names", "used"}]: the scope's character ranges, the names renamed there and those used) and
"""
    def unit(uid, s, e, names):
        names = [x for x in names if x != "_"]
        if len(names) != len(set(names)):
            return False
        site.units.append({"id": uid, "s": s, "e": e, "names": names, "used": set()})
        return True
    if site.kind == "induction":
        for al in site.alts:
            if al["inline"]:
                ln = B.lines[al["li"]]
                s = B.starts[al["li"]] + ln.index("=>") + 2
                e = B.starts[al["li"]] + len(ln)
            else:
                s, e = _span(B, al["li"] + 1, al["end"])
            if not unit("alt:" + al["tag"], s, e, al["names"]):
                return False
    else:
        bullet = "·" in site.lead
        a, b = site.li + 1, B.block_end(site.li, strict=bullet)
        s, e = _span(B, a, b)
        if site.goals > 1:                                                                               
            if not unit("main", s, e, sorted(set(site.names))):
                return False
            bl = _bullets(B, a, b, site.col)
            if bl is not None and len(bl) == site.goals:
                for g, (x, y) in enumerate(bl):
                    unit(f"goal{g}", *_span(B, x, y), [site.names[g]])
        elif not unit("main", s, e, site.names):
            return False
    for u in site.units:
        words = _words(B, u["s"], u["e"])
        if "rename_i" in words or ("_" in site.names and words & {"case", "next"}):
            return False
        for n in u["names"]:
            r = _refs(B, S, u["s"], u["e"], n)
            if r is None:
                return False
            if r:
                u["used"].add(n)
                site.used.add(n)
    return True


class Prep:
    """A proof prepared for T4: head, body, the T2 line structure, the sites (with scopes) and the regions."""

    def __init__(self, proof: str, statement: str):
        self.ok = False
        body = split_declaration(proof, statement)
        if body is None:
            return
        self.proof, self.statement, self.body = proof, statement, body
        self.head = proof[:len(proof) - len(body)]
        self.B = T2._Body(body)
        if self.B.fb < 0:
            return
        self.S = T1.Src(body, statement)
        self.regions = _regions(self.B)
        self.sites: list[Site] = []
        for li in range(len(self.B.lines)):
            st = _site_at(self.B, li)
            if st is None or not _scopes(self.B, self.S, st):
                continue
            st.inside = any(a <= li < b for a, b in self.regions)
            self.sites.append(st)
        self.by_key = {s.key: s for s in self.sites}
        self.ok = True

    def decl_line(self, body_li: int) -> int:
        return self.head.count("\n") + body_li + 1


def _needs_probe(st: Site) -> bool:
    return bool(st.used)


def _heads_ok(text: str) -> bool:
    """Every head T4 writes in `text` is present on every toolchain (TABLES["t4_heads"])."""
    for h in HEADS:
        if re.search(_ID_L + re.escape(h) + _ID_R, text) and h not in AVAILABLE:
            return False
    return True


                                                                                                                                    
def _subst_body(P: Prep, maps: dict) -> str | None:
    """The body with every use renamed: maps {site key: {unit id: {old: new}}}; None on overlapping edits."""
    edits = []
    for key, units in maps.items():
        st = P.by_key[key]
        for u in st.units:
            mp = units.get(u["id"])
            if not mp:
                continue
            for old, new in mp.items():
                if old == new:
                    continue
                for i in _refs(P.B, P.S, u["s"], u["e"], old) or []:
                    edits.append((i, i + len(old), new))
    edits.sort()
    for (a, b, _), (c, _, _) in zip(edits, edits[1:]):
        if c < b:
            return None
    out, p = [], 0
    for a, b, new in edits:
        out.append(P.body[p:a])
        out.append(new)
        p = b
    out.append(P.body[p:])
    return "".join(out)


def _dedent_to(lines: list[str], col: int) -> list[str]:
    ind = min((len(x) - len(x.lstrip(" \t")) for x in lines if x.strip()), default=0)
    return [(" " * col + x[ind:]) if x.strip() else "" for x in lines]


def _replacement(B, st: Site, fid: str, wrap: bool, order, trace: bool) -> tuple[list[str], int | None] | None:
    """(lines replacing the site's [li, end), index of the trace line among them or None); B is the (renamed) body's structure.
"""
    form = dict(st.forms).get(fid)
    if form is None:
        return None
    first = st.lead + (WRAP + " " if wrap else "") + form
    out, tr = [first], None
    if trace:
        out.append(" " * st.col + TRACE)
        tr = 1
    if st.kind != "induction" or order is None:
        return out, tr
    alts = {al["tag"]: al for al in st.alts}
    if sorted(order) != sorted(alts):
        return None
    for tag in order:
        al = alts[tag]
        if al["inline"]:
            ln = B.lines[al["li"]]
            rhs = ln[ln.index("=>") + 2:].strip()
            out.append(" " * st.col + "· " + rhs)
        else:
            blk = _dedent_to(B.lines[al["li"] + 1:al["end"]], st.col + 2)
            k = next((i for i, x in enumerate(blk) if x.strip() and not x.strip().startswith("--")), None)
            if k is None:
                return None
            out += blk[:k] + [" " * st.col + "· " + blk[k].lstrip()] + blk[k + 1:]
    return out, tr


def build(P: Prep, chosen: list[tuple], *, maps: dict | None = None, trace: bool = False, region: int | None = None):
    """(body, {site key: trace body line}) with the sites of `chosen` [(key, fid, wrap, order)] rewritten (their line ranges must not

"""
    nb = _subst_body(P, maps or {}) if maps else P.body
    if nb is None:
        return None
    B = T2._Body(nb) if nb != P.body else P.B
    if len(B.lines) != len(P.B.lines):
        return None
    chosen = sorted(chosen, key=lambda c: P.by_key[c[0]].li)
    out, cur, traces = [], 0, {}
    for key, fid, wrap, order in chosen:
        st0 = P.by_key[key]
        if st0.li < cur:
            return None
        st = _site_at(B, st0.li) if nb != P.body else st0
        if st is None or st.kind != st0.kind or st.end != st0.end:
            return None
        rep = _replacement(B, st, fid, wrap, order, trace)
        if rep is None:
            return None
        lines, tr = rep
        out += B.lines[cur:st.li]
        if tr is not None:
            traces[key] = len(out) + tr
        out += lines
        cur = st.end
    out += B.lines[cur:]
    if region is not None:
        ind = P.B.ind(region)
        out.insert(region, " " * ind + WRAP)
        traces = {k: (v + 1 if v >= region else v) for k, v in traces.items()}
    return "\n".join(out), traces


def orig_with_traces(P: Prep, sites: list[Site]) -> tuple[str, dict]:
    """The proof body with `trace_state` after each intro / rcases site and as the first tactic of each induction alternative:
"""
    ins: dict = {}                                                                                                                  
    for st in sites:
        if st.kind != "induction":
            ins.setdefault(st.li, []).append(("after", " " * st.col + TRACE, (st.key, "main")))
            continue
        for al in st.alts:
            if al["inline"]:
                ins.setdefault(al["li"], []).append(("inline", None, (st.key, "alt:" + al["tag"])))
            else:
                j = al["li"] + 1
                while P.B.blank(j):
                    j += 1
                ins.setdefault(j - 1, []).append(("after", " " * P.B.ind(j) + TRACE, (st.key, "alt:" + al["tag"])))
    out, where = [], {}
    for li, ln in enumerate(P.B.lines):
        for pos, _, tk in ins.get(li, []):
            if pos == "inline":
                k = ln.index("=>") + 2
                ln = ln[:k] + " " + TRACE + ";" + ln[k:]
                where[tk] = len(out)
        out.append(ln)
        for pos, text, tk in ins.get(li, []):
            if pos == "after":
                where[tk] = len(out)
                out.append(text)
    return "\n".join(out), where


                                                                                                                                     
def _norm(s: str) -> str:
    return " ".join(str(s).split())


def parse_goals(data) -> list[dict] | None:
    """Lean's goal display (`trace_state`): [{"tag", "hyps": [[name, type]], "target"}], [] for "no goals", None when not a goal list."""
    s = str(data or "").strip("\n")
    if not s.strip():
        return None
    if s.strip() == "no goals":
        return []
    goals = []
    for blk in re.split(r"\n[ \t]*\n", s):
        lines = blk.split("\n")
        tag = None
        if lines and lines[0].startswith("case "):
            tag, lines = lines[0][5:].strip(), lines[1:]
        ents: list = []
        for ln in lines:
            if not ln.strip():
                continue
            if ln[:1] in (" ", "\t"):
                if not ents:
                    return None
                ents[-1][1] += " " + ln.strip()
            elif ln.startswith("⊢"):
                ents.append(["goal", ln[1:].strip()])
            elif " : " in ln or ln.rstrip().endswith(" :"):                                                                
                ents.append(["hyp", ln.rstrip()])
            else:
                return None
        if not ents or ents[-1][0] != "goal" or sum(1 for k, _ in ents if k == "goal") != 1:
            return None
        hyps = []
        for kind, text in ents[:-1]:
            names, typ = text.split(" : ", 1)
            for n in names.split():
                if not re.fullmatch(r"[^\W\d][" + _PPC + r"]*|«[^»]*»", n):
                    return None
                hyps.append([n, _norm(typ)])
        goals.append({"tag": tag, "hyps": hyps, "target": _norm(ents[-1][1])})
    return goals


def trace_at(messages, line: int) -> list | None:
    """The goals of the single `trace_state` message at declaration line `line` (None: none, several, or not a goal display)."""
    got = []
    for m in messages or []:
        ln = m.get("decl_line") if m.get("decl_line") is not None else (m.get("pos") or {}).get("line")
        if ln != line or m.get("severity") != "information":
            continue
        g = parse_goals(m.get("data"))
        if g is not None:
            got.append(g)
    return got[0] if len(got) == 1 else None


def _inacc(n: str) -> bool:
    return "✝" in n


def _valid(n: str) -> bool:
    return bool(_NAME_FULL.fullmatch(n)) and n not in KEYWORDS and n not in NOT_NAMES and not re.search(r"[¹²³⁴⁵⁶⁷⁸⁹⁰]", n)


def _subst(text: str, mp: dict) -> str:
    return _PPID.sub(lambda m: mp.get(m.group(1), m.group(1)), text) if mp else text


def align(O: dict, N: dict, names, used) -> tuple[dict, list] | None:
    """One goal under the original names (O) and after the nameless tactic (N): ({used name: Lean's name}, [new accessible names])
"""
    if len(O["hyps"]) != len(N["hyps"]):
        return None
    names, used = set(names), set(used)
    full, rename, fresh = {}, {}, []
    for (on, _), (nn, _) in zip(O["hyps"], N["hyps"]):
        if on != nn:
            if not _inacc(on) and on not in names:
                return None                                                                     
            if _inacc(nn):
                if on in used:
                    return None
            else:
                if not _valid(nn):
                    return None
                fresh.append(nn)
            if on in full:
                return None
            full[on] = nn
        if on in used:
            rename[on] = nn
    if not used <= set(rename):
        return None
    if len(set(rename.values())) != len(rename):
        return None
    for (_, ot), (_, nt) in zip(O["hyps"], N["hyps"]):
        if _norm(_subst(ot, full)) != nt:
            return None
    if _norm(_subst(O["target"], full)) != N["target"]:
        return None
    return rename, fresh


def _unit(st: Site, uid: str) -> dict | None:
    return next((u for u in st.units if u["id"] == uid), None)


def _captures(P: Prep, st: Site, uid: str, rename: dict, fresh: list) -> bool:
    """Does a new name occur in the unit's scope other than as a name being renamed away (or is there no such unit)?"""
    u = _unit(st, uid)
    if u is None:
        return True
    words = _words(P.B, u["s"], u["e"])
    return any(f in words and f not in rename for f in fresh)


def site_maps(P: Prep, st: Site, orig: dict, goals: list | None):
    """({unit id: rename}, induction order or None) from the traces of one (site, form): `orig` {trace id: goals} under the original
"""
    if goals is None or not orig:
        return None
    if st.kind == "induction":
        if len(goals) != len(st.alts):
            return None
        units, order = {}, []
        for g in goals:
            tag = g.get("tag")
            u = _unit(st, f"alt:{tag}")
            if u is None or tag in order:
                return None
            O = orig.get(u["id"])
            if not O or len(O) != 1:
                return None
            r = align(O[0], g, u["names"], u["used"])
            if r is None or _captures(P, st, u["id"], *r):
                return None
            units[u["id"]] = r[0]
            order.append(tag)
        return units, order
    O = orig.get("main")
    main = _unit(st, "main")
    if not O or main is None or len(O) != len(goals) or len(goals) != st.goals:
        return None
    if any(o.get("tag") and g.get("tag") and o["tag"] != g["tag"] for o, g in zip(O, goals)) \
            and "case" in _words(P.B, main["s"], main["e"]):
        return None
    if st.goals == 1:
        r = align(O[0], goals[0], main["names"], main["used"])
        if r is None or _captures(P, st, "main", *r):
            return None
        return {"main": r[0]}, None
    bul = [_unit(st, f"goal{g}") for g in range(st.goals)]                                          
    if all(u is not None for u in bul):
        units = {}
        for o, n, u in zip(O, goals, bul):
            r = align(o, n, u["names"], u["used"])
            if r is None or _captures(P, st, u["id"], *r):
                return None
            units[u["id"]] = r[0]
        return units, None
    union, fresh = {}, []
    for g, (o, n) in enumerate(zip(O, goals)):
        nm = [st.names[g]] if st.names[g] != "_" else []
        r = align(o, n, nm, main["used"] & set(nm))
        if r is None:
            return None
        for k, v in r[0].items():
            if union.get(k, v) != v:
                return None
            union[k] = v
        fresh += r[1]
    if _captures(P, st, "main", union, fresh):
        return None
    return {"main": union}, None


                                                                                                                                     
def _top_region(P: Prep) -> int | None:
    """The body line before which one `unhygienic` line covers the whole tactic block (the body is `by` + an indented block), or None."""
    L = P.B.lines
    if not L or P.B.code(0).strip() != "by":
        return None
    j = 1
    while j < len(L) and P.B.blank(j):
        j += 1
    if j >= len(L) or P.B.ind(j) == 0:
        return None
    t = P.B.ind(j)
    if any(not P.B.blank(k) and P.B.ind(k) < t for k in range(j, len(L))):
        return None
    return j


def _probe_sites(P: Prep) -> list[Site]:
    """The sites to probe: those with a used name, most tokens saved first (then line), at most PROBE_MAX_SITES."""
    t0 = count_tokens(P.body)
    ranked = []
    for st in P.sites:
        if not _needs_probe(st):
            continue
        best = None
        for fid, _ in st.forms:
            order = [al["tag"] for al in st.alts] if st.kind == "induction" else None
            b = build(P, [(st.key, fid, not st.inside, order)])
            if b is not None:
                d = count_tokens(b[0]) - t0
                best = d if best is None else min(best, d)
        if best is not None:
            ranked.append((best, st.li, st))
    ranked.sort(key=lambda x: (x[0], x[1]))
    return [st for _, _, st in ranked[:PROBE_MAX_SITES]]


def _verify_round1(P: Prep, res: dict) -> dict:
    """{site key: (fid, units, order, tokens)}: per site the verified form with the fewest tokens (bare: the round-2 configuration)."""
    out = {}
    t0 = count_tokens(P.body)
    for key, r in (res.get("sites") or {}).items():
        st = P.by_key.get(key)
        if st is None:
            continue
        best = None
        for fid, _ in st.forms:
            sm = site_maps(P, st, r.get("orig") or {}, (r.get("forms") or {}).get(fid))
            if sm is None:
                continue
            b = build(P, [(key, fid, False, sm[1])], maps={key: sm[0]})
            if b is None or not _heads_ok(b[0]):
                continue
            d = count_tokens(b[0]) - t0
            if best is None or d < best[3]:
                best = (fid, sm[0], sm[1], d)
        if best is not None:
            out[key] = best
    return out


def _all_set(P: Prep, ver: dict) -> list[str]:
    """Round-2 sites: verified, not nested inside another chosen site's lines, in line order."""
    keys = sorted(ver, key=lambda k: P.by_key[k].li)
    out, end = [], -1
    for k in keys:
        st = P.by_key[k]
        if st.li < end:
            continue
        out.append(k)
        end = st.end
    return out


def probe(proof: str, statement: str, compile_batch, *, ctx: dict | None = None, stats: dict | None = None, log=None) -> dict:
    """Ask Lean for the names of every probed site (module docstring, "probe"): {"t4_probe": result, "t4_probe_for": key} or {} when
"""
    st_ = stats if stats is not None else {}
    log = log or (lambda m: None)
    for c in ("probes", "judged", "sites", "verified", "round2"):
        st_.setdefault(c, 0)
    P = Prep(proof, statement)
    if not P.ok or not AVAILABLE >= {"trace_state", WRAP}:
        return {}
    sites = _probe_sites(P)
    if not sites:
        return {}
    ob, where = orig_with_traces(P, sites)
    texts, idx = [P.head + ob], []
    for st in sites:
        for fid, _ in st.forms:
            order = None
            b = build(P, [(st.key, fid, not st.inside, order)], trace=True)
            if b is None or st.key not in b[1] or not _heads_ok(b[0]):
                continue
            texts.append(P.head + b[0])
            idx.append((st.key, fid, b[1][st.key]))
    got = compile_batch(texts)
    got = list(got or []) + [None] * (len(texts) - len(got or []))
    st_["probes"] += len(texts)
    st_["judged"] += sum(1 for g in got if g is not None)
    st_["sites"] += len(sites)
    res = {"sites": {}}
    om = got[0]
    for st in sites:
        orig = {}
        if om is not None:
            for (key, tid), ln in where.items():
                if key == st.key:
                    orig[tid] = trace_at(om, P.decl_line(ln))
        res["sites"][st.key] = {"orig": orig, "forms": {}}
    for (key, fid, ln), msgs in zip(idx, got[1:]):
        res["sites"][key]["forms"][fid] = trace_at(msgs, P.decl_line(ln)) if msgs is not None else None
    ver = _verify_round1(P, res)
    st_["verified"] += len(ver)
    log(f"t4 probe: {len(sites)} site(s), {len(texts)} copies, {len(ver)} verified")
    keys = _all_set(P, ver)
    region = None if all(P.by_key[k].inside for k in keys) else _top_region(P)
    if len(keys) >= 2 and (region is not None or all(P.by_key[k].inside for k in keys)) \
            and not _words(P.B, 0, len(P.body)) & {"rename_i", "case", "next"}:
        chosen = [(k, ver[k][0], False, ver[k][2]) for k in keys]
        b = build(P, chosen, maps={k: ver[k][1] for k in keys}, trace=True, region=region)
        if b is not None and _heads_ok(b[0]):
            g2 = compile_batch([P.head + b[0]])
            m2 = (list(g2 or []) + [None])[0]
            st_["round2"] += 1
            st_["probes"] += 1
            st_["judged"] += m2 is not None
            res["all"] = {"keys": keys, "region": region, "fids": {k: ver[k][0] for k in keys},
                          "traces": {k: (trace_at(m2, P.decl_line(ln)) if m2 is not None else None) for k, ln in b[1].items()}}
    return {"t4_probe": res, "t4_probe_for": proof_key(proof)}


                                                                                                                                     
def _note(P: Prep, chosen: list, maps: dict) -> str:
    parts = []
    for key, fid, wrap, _ in chosen:
        st = P.by_key[key]
        ren = ", ".join(dict.fromkeys(f"{o}→{n}" for u in (maps.get(key) or {}).values() for o, n in sorted(u.items()) if o != n))
        parts.append(f"{P.B.lines[st.li].strip()[:28]} -> {(WRAP + ' ') if wrap else ''}{dict(st.forms)[fid][:24]}"
                     + (f" [{ren}]" if ren else "") + f" @L{P.decl_line(st.li)}")
    return "; ".join(parts)[:300]


def _all_candidate(P: Prep, res: dict, ver: dict):
    """(chosen, maps, region) of t4:all from round 2, or None."""
    a = res.get("all") or {}
    keys, region, tr = a.get("keys") or [], a.get("region"), a.get("traces") or {}
    if len(keys) < 2 or any(k not in ver or k not in P.by_key for k in keys):
        return None
    chosen, maps = [], {}
    for k in keys:
        st = P.by_key[k]
        fid = (a.get("fids") or {}).get(k, ver[k][0])
        r = (res.get("sites") or {}).get(k) or {}
        sm = site_maps(P, st, r.get("orig") or {}, tr.get(k))
        if sm is None:
            break
        chosen.append((k, fid, False, sm[1]))
        maps[k] = sm[0]
        if sm[0] != ver[k][1] or sm[1] != ver[k][2]:
            break                                                                                               
    if len(chosen) < 2:
        return None
    return chosen, maps, region


def candidates(proof: str, statement: str, *, exchange: float | None = None, max_per_op: int = MAX_PER_OP,
               ctx: dict | None = None) -> list[dict]:
    """[{"op", "decl", "note"}] (module docstring): pure; the probe's names come in ctx["t4_probe"] (for ctx["t4_probe_for"] ==
"""
    P = Prep(proof, statement)
    if not P.ok or not AVAILABLE:
        return []
    ops = _ops(ctx)
    t0 = count_tokens(P.body)
    res = (ctx or {}).get("t4_probe") if (ctx or {}).get("t4_probe_for") == proof_key(proof) else None
    res = res if isinstance(res, dict) else {}
    found: list = []                                                        
    for st in P.sites:
        if st.op not in ops:
            continue
        if not st.used:                                                                               
            if st.kind == "intro":
                continue
            order = [al["tag"] for al in st.alts] if st.kind == "induction" else None
            for rank, (fid, _) in enumerate(st.forms):
                found.append((st.op, rank, [(st.key, fid, False, order)], {}, None))
            continue
        r = (res.get("sites") or {}).get(st.key)
        if not r:
            continue
        for rank, (fid, _) in enumerate(st.forms):
            sm = site_maps(P, st, r.get("orig") or {}, (r.get("forms") or {}).get(fid))
            if sm is not None:
                found.append((st.op, rank, [(st.key, fid, not st.inside, sm[1])], {st.key: sm[0]}, None))
    if "t4:all" in ops and res.get("all"):
        ver = _verify_round1(P, res)
        ac = _all_candidate(P, res, ver)
        if ac is not None:
            found.append(("t4:all", 0, ac[0], ac[1], ac[2]))
    rows, seen = [], {proof.strip()}
    for op, rank, chosen, maps, region in found:
        b = build(P, chosen, maps=maps, region=region)
        if b is None or not _heads_ok(b[0]):
            continue
        decl = P.head + b[0]
        if decl.strip() in seen or split_declaration(decl, statement) != b[0]:
            continue
        tok = count_tokens(b[0])
        if tok >= t0:
            continue
        seen.add(decl.strip())
        rows.append((tok, OPS.index(op), P.by_key[chosen[0][0]].li, rank, {"op": op, "decl": decl, "note": _note(P, chosen, maps)}))
    rows.sort(key=lambda x: x[:4])
    out, per = [], {}
    for *_, c in rows:
        if per.get(c["op"], 0) >= max_per_op:
            continue
        per[c["op"]] = per.get(c["op"], 0) + 1
        out.append(c)
    return out


def sites_summary(proof: str, statement: str) -> list[dict]:
    """The sites found (for the CLI and the tests): [{"key", "op", "line", "names", "used", "inside", "forms"}]."""
    P = Prep(proof, statement)
    if not P.ok:
        return []
    return [{"key": s.key, "op": s.op, "line": P.decl_line(s.li), "names": s.names, "used": sorted(s.used), "inside": s.inside,
             "forms": [f for _, f in s.forms]} for s in P.sites]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="T4 nameless candidates of one declaration (no compile)")
    ap.add_argument("--file", required=True, help="the declaration (statement := body)")
    ap.add_argument("--statement-file", required=True, help="the exact statement text")
    ap.add_argument("--probe-json", default=None, help="a probe() result (JSON) for this proof")
    ap.add_argument("--max-per-op", type=int, default=MAX_PER_OP)
    a = ap.parse_args(argv)
    proof = Path(a.file).read_text()
    stmt = Path(a.statement_file).read_text().rstrip("\n")
    ctx = json.loads(Path(a.probe_json).read_text()) if a.probe_json else None
    for s in sites_summary(proof, stmt):
        print(json.dumps({"site": s}, ensure_ascii=False))
    t0 = count_tokens(split_declaration(proof, stmt) or "")
    for d in candidates(proof, stmt, max_per_op=a.max_per_op, ctx=ctx):
        print(json.dumps({"op": d["op"], "note": d["note"], "dtok": count_tokens(split_declaration(d["decl"], stmt)) - t0},
                         ensure_ascii=False))
    return 0


